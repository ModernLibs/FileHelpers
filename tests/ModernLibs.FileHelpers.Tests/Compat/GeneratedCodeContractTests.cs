    [Test]
    [DisplayName("Every member that 4.8 and 4.9 generated code binds to exists with the listed parameter types")]
    public async Task Every_Listed_Member_Exists()
    {
        // Act
        var missing = Contract.Where(c => !c.Exists()).Select(c => c.Member).ToArray();

        // Assert
        await Assert.That(Contract.Length).IsBetween(30, 45);
        await Assert.That(string.Join("\n", missing)).IsEqualTo(string.Empty);
    }

    private static (string, Func<bool>) Method(Type type, string name, Type returnType, params Type[] parameters) =>
        ($"{Show(type)}.{name}({string.Join(", ", parameters.Select(Show))})", () => HasMethod(type, name, returnType, parameters));

    private static (string, Func<bool>) Ctor(Type type, params Type[] parameters) =>
        ($"{Show(type)}({string.Join(", ", parameters.Select(Show))})", () => HasCtor(type, parameters));

    private static (string, Func<bool>) Property(Type type, string name, Type propertyType) =>
        ($"{Show(type)}.{name} {{ get; }} : {Show(propertyType)}", () =>
            type.GetProperty(name, Any) is { GetMethod.IsPublic: true } p && p.PropertyType == propertyType);

    private static (string, Func<bool>) Init(string name, Type propertyType) =>
        ($"RecordOptions.{name} {{ get; init; }} : {Show(propertyType)}", () =>
            typeof(RecordOptions).GetProperty(name, Any) is { GetMethod.IsPublic: true, SetMethod.IsPublic: true } p
            && p.PropertyType == propertyType
            && p.SetMethod.ReturnParameter.GetRequiredCustomModifiers().Contains(typeof(IsExternalInit)));

    private static (string, Func<bool>) Values<TEnum>(params (TEnum Value, int Number)[] values)
        where TEnum : struct, Enum =>
        ($"{typeof(TEnum).Name} values {string.Join(", ", values.Select(v => $"{v.Value}={v.Number}"))}", () =>
            Enum.GetUnderlyingType(typeof(TEnum)) == typeof(int)
            && values.All(v => Convert.ToInt32(v.Value, CultureInfo.InvariantCulture) == v.Number));

    private static (string, Func<bool>) Converters(string description, Type[] types, params Type[][] constructors) =>
        (description, () => types.All(t =>
            t.GetField("Instance", Any) is { IsStatic: true, IsInitOnly: true } f && f.FieldType == t
            && constructors.All(c => HasCtor(t, c))));

    private static bool HasMethod(Type type, string name, Type returnType, params Type[] parameters) =>
        type.GetMethod(name, Any, parameters) is { IsPublic: true } m && m.ReturnType == returnType;

    private static bool HasCtor(Type type, params Type[] parameters) =>
        type.GetConstructor(BindingFlags.Public | BindingFlags.Instance, parameters) is not null;

    private static string Show(Type type) =>
        type == typeof(Rec) ? "T"
        : type.IsByRef ? "out " + Show(type.GetElementType()!)
        : type.IsGenericType ? $"{type.Name[..type.Name.IndexOf('`', StringComparison.Ordinal)]}<{string.Join(", ", type.GetGenericArguments().Select(Show))}>"
        : type.Name;
}
