    // Converters
    // ---------------------------------------------------------------------------------------------

    /// <summary>How a field is converted: the converter expression, its value type and an optional cached instance.</summary>
    private sealed class ConverterPlan
    {
        public ConverterPlan(string expression, string valueType, bool unwrapNullable, string? declaration, ConverterOrigin origin)
        {
            Expression = expression;
            ValueType = valueType;
            UnwrapNullable = unwrapNullable;
            Declaration = declaration;
            Origin = origin;
        }

        /// <summary>Expression evaluating to the <c>ISpanConverter&lt;T&gt;</c> instance.</summary>
        public string Expression { get; }

        /// <summary>The converter's <c>T</c>.</summary>
        public string ValueType { get; }

        /// <summary>True when the field is <c>T?</c> and the converter converts <c>T</c>.</summary>
        public bool UnwrapNullable { get; }

        /// <summary>Declaration of the cached converter field (type and initializer), or null for <c>.Instance</c>.</summary>
        public string? Declaration { get; }

        public ConverterOrigin Origin { get; }
    }

    private enum ConverterOrigin
    {
        BuiltIn,
        ConverterBase,
        SpanConverter,
    }

    /// <summary>
    /// Resolves the converter for a field (custom type, explicit <c>ConverterKind</c> with its arguments,
    /// or the implicit built-in converter for the field type). Returns null for <c>string</c> and
    /// unsupported fields, which need no conversion.
    /// The same plan drives parsing AND formatting, so converter arguments are honoured on write.
    /// </summary>
    private static ConverterPlan? GetConverterPlan(FieldModel field, int index)
    {
        string cached = $"{ConverterHolder}.__conv_field{index}";

        if (field.ConverterKind == GeneratorConverterKind.None && field.ConverterTypeName is not null)
        {
            // [FieldConverter(typeof(X), args...)]: the arguments go to the constructor chosen by the extractor.
            var customArgList = new List<string>(field.ConverterArgs.Length);
            foreach (string arg in field.ConverterArgs)
                customArgList.Add(Literal(arg));
            string customArgs = string.Join(", ", customArgList);
            if (field.DirectSpanConverter)
            {
                string valueType = field.ConverterTargetsUnderlying ? field.UnderlyingTypeName : field.FullTypeName;
                return new ConverterPlan(cached, valueType, field.ConverterTargetsUnderlying,
                    $"{field.ConverterTypeName} __conv_field{index} = new({customArgs})", ConverterOrigin.SpanConverter);
            }

            string adapter = $"{Converters}ConverterBaseAdapter<{field.FullTypeName}>";
            return new ConverterPlan(cached, field.FullTypeName, unwrapNullable: false,
                $"{adapter} __conv_field{index} = new(new {field.ConverterTypeName}({customArgs}))", ConverterOrigin.ConverterBase);
        }

        if (field.ValueKind is FieldValueKind.String or FieldValueKind.Unsupported)
            return null;

        string converterClass = field.ConverterKind switch
        {
            GeneratorConverterKind.PercentDouble => Converters + "PercentDoubleConverter",
            GeneratorConverterKind.DateMultiFormat => Converters + "DateMultiFormatConverter",
            _ => BuiltInConverterClass(field.ValueKind, field.UnderlyingTypeName),
        };

        string? ctorArgs = BuildConverterArguments(field);
        if (ctorArgs is null)
            return new ConverterPlan(converterClass + ".Instance", field.UnderlyingTypeName, field.IsNullableValueType, null, ConverterOrigin.BuiltIn);

        return new ConverterPlan(cached, field.UnderlyingTypeName, field.IsNullableValueType,
            $"{converterClass} __conv_field{index} = new({ctorArgs})", ConverterOrigin.BuiltIn);
    }

    private static string BuiltInConverterClass(FieldValueKind kind, string underlyingType) => kind switch
    {
        FieldValueKind.Boolean => Converters + "BoolConverter",
        FieldValueKind.Char => Converters + "CharConverter",
        FieldValueKind.Byte => Converters + "ByteConverter",
        FieldValueKind.SByte => Converters + "SByteConverter",
        FieldValueKind.Int16 => Converters + "Int16Converter",
        FieldValueKind.UInt16 => Converters + "UInt16Converter",
        FieldValueKind.Int32 => Converters + "Int32Converter",
        FieldValueKind.UInt32 => Converters + "UInt32Converter",
        FieldValueKind.Int64 => Converters + "Int64Converter",
        FieldValueKind.UInt64 => Converters + "UInt64Converter",
        FieldValueKind.Decimal => Converters + "DecimalConverter",
        FieldValueKind.Double => Converters + "DoubleConverter",
        FieldValueKind.Single => Converters + "SingleConverter",
        FieldValueKind.DateTime => Converters + "DateTimeConverter",
        FieldValueKind.DateOnly => Converters + "DateOnlyConverter",
        FieldValueKind.TimeOnly => Converters + "TimeOnlyConverter",
        FieldValueKind.DateTimeOffset => Converters + "DateTimeOffsetConverter",
        FieldValueKind.TimeSpan => Converters + "TimeSpanConverter",
        FieldValueKind.Guid => Converters + "GuidConverter",
        FieldValueKind.Enum => $"{Converters}EnumConverter<{underlyingType}>",
        _ => throw new InvalidOperationException($"No built-in converter for {kind}."),
    };

    /// <summary>
    /// Constructor arguments for a configured built-in converter (FileHelpers 3.x
    /// <c>[FieldConverter(kind, args)]</c> semantics), or null when the shared <c>.Instance</c> applies.
    /// A bare <c>null</c> argument is never emitted where overloads would make it ambiguous.
    /// </summary>
    private static string? BuildConverterArguments(FieldModel field)
    {
        var args = field.ConverterArgs;
        string? first = args.Length > 0 && args[0].Length > 0 ? args[0] : null;
        string? culture = string.IsNullOrEmpty(field.CultureName) ? null : CultureExpression(field.CultureName!);

        if (field.ConverterKind == GeneratorConverterKind.DateMultiFormat)
        {
            var formats = new StringBuilder("new string[] { ");
            for (int i = 0; i < args.Length; i++)
            {
                if (i > 0) formats.Append(", ");
                formats.Append(Literal(args[i]));
            }
            formats.Append(" }");
            return culture is null ? formats.ToString() : $"{formats}, {culture}";
        }

        switch (field.ValueKind)
        {
            case FieldValueKind.DateTime:
            {
                // 3.x ConverterKind.Date: arg 1 = format, arg 2 = culture name.
                string? dateCulture = args.Length > 1 && args[1].Length > 0 ? CultureExpression(args[1]) : culture;
                if (first is null && dateCulture is null) return null;
                return $"{(first is null ? "null" : Literal(first))}, {dateCulture ?? "null"}";
            }
            case FieldValueKind.DateOnly:
            case FieldValueKind.TimeOnly:
            case FieldValueKind.DateTimeOffset:
            case FieldValueKind.TimeSpan:
                return culture is null ? null : $"null, {culture}";
            case FieldValueKind.Byte:
            case FieldValueKind.SByte:
            case FieldValueKind.Int16:
            case FieldValueKind.UInt16:
            case FieldValueKind.Int32:
            case FieldValueKind.UInt32:
            case FieldValueKind.Int64:
            case FieldValueKind.UInt64:
            case FieldValueKind.Decimal:
            case FieldValueKind.Double:
            case FieldValueKind.Single:
                // Arg 1 = decimal separator ("." / ",") or culture name; CultureName otherwise.
                if (first is not null) return Literal(first);
                return culture;
            case FieldValueKind.Boolean:
                return args.Length >= 2 ? $"{Literal(args[0])}, {Literal(args[1])}" : null;
            case FieldValueKind.Char:
            case FieldValueKind.Guid:
                return first is null ? null : Literal(first);
            default:
                return null;
        }
    }

    private static string CultureExpression(string cultureName) =>
        $"global::System.Globalization.CultureInfo.GetCultureInfo({Literal(cultureName)})";

    /// <summary>
    /// Cached converter instances live in a nested static class so they are created on first use rather
    /// than when the descriptor is registered: an invalid converter argument then surfaces when the record
    /// is read or written instead of breaking the module initializer of the whole assembly.
    /// </summary>
    private static void EmitConverterHolder(StringBuilder sb, ConverterPlan?[] plans)
    {
        bool any = false;
        foreach (var plan in plans)
        {
            if (plan?.Declaration is not null)
            {
                any = true;
                break;
            }
        }
        if (!any) return;

        sb.AppendLine($"    private static class {ConverterHolder}");
        sb.AppendLine("    {");
        foreach (var plan in plans)
        {
            if (plan?.Declaration is null) continue;
            if (plan.Origin == ConverterOrigin.ConverterBase)
                sb.AppendLine("        // Legacy ConverterBase adapter — allocates strings per field. Implement ISpanConverter<T> for zero-alloc.");
            sb.AppendLine($"        internal static readonly {plan.Declaration};");
        }
        sb.AppendLine("    }");
        sb.AppendLine();
    }

