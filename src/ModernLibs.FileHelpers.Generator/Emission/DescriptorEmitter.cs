    private static int ExpectedLineCount(EquatableArray<FieldModel> fields)
    {
        int lines = 1;
        foreach (var f in fields)
        {
            if (f.IsInNewLine) lines++;
        }
        return lines;
    }

    private static bool HasAnyQuotedField(EquatableArray<FieldModel> fields)
    {
        foreach (var f in fields)
        {
            if (f.IsQuoted) return true;
        }
        return false;
    }

    /// <summary>
    /// Emits the shared parse prologue (line-count check, multi-line split, fixed-length validation,
    /// quoted-buffer rentals, field splitting, quote strip, trim, not-empty validation and conversions).
    /// Returns true when the caller must close a try/finally for quote rentals.
    /// </summary>
    private static bool EmitParsePrologue(StringBuilder sb, RecordModel model, ConverterPlan?[] plans)
    {
        var fields = model.Fields;
        int expectedLineCount = ExpectedLineCount(fields);
        bool hasMultiLine = expectedLineCount > 1;
        bool isDelimited = string.Equals(model.RecordKind, "Delimited", StringComparison.Ordinal);
        bool hasQuotedField = HasAnyQuotedField(fields);

        // Multi-line records: one physical line per [FieldInNewLine] field plus the first line.
        sb.AppendLine($"        const int __expectedLines = {expectedLineCount}; // 1 + {expectedLineCount - 1} FieldInNewLine fields");
        sb.AppendLine("        if (lineCount != __expectedLines)");
        sb.AppendLine("            throw new global::ModernLibs.FileHelpers.BadUsageException($\"Expected {__expectedLines} lines for the record but received {lineCount}. Check that all multi-line fields are present.\");");
        sb.AppendLine("        var line = lines;");
        sb.AppendLine();

        if (hasMultiLine)
        {
            EmitMultiLineSplitting(sb, model, expectedLineCount);
            if (fields[0].IsInNewLine)
                EmitBlankFirstLineValidation(sb, fields[0]);
        }

        if (!isDelimited)
            EmitFixedLengthModeValidation(sb, fields, model.FixedMode, hasMultiLine);

        // Each quoted field may rent a char[] for unescaping; returned in finally.
        if (hasQuotedField)
        {
            for (int i = 0; i < fields.Length; i++)
            {
                if (fields[i].IsQuoted)
                    sb.AppendLine($"        char[]? __qRent{i} = null;");
            }
            sb.AppendLine("        try");
            sb.AppendLine("        {");
        }

        if (isDelimited)
            EmitDelimitedFieldSplitting(sb, model, hasMultiLine);
        else
            EmitFixedLengthFieldSplitting(sb, fields, hasMultiLine);

        // Strip quotes BEFORE trim, then trim, then check [FieldNotEmpty] on the trimmed value.
        // Delimited: the splitter already located the quoted section (3.x DelimitedField). Fixed-length:
        // trimmed quoted fields are trimmed first so blanks around the quotes do not prevent unquoting.
        if (!isDelimited)
            EmitFieldTrimPass(sb, fields, quotedOnly: true);
        EmitFieldQuotedStripPass(sb, fields, isDelimited);
        EmitFieldTrimPass(sb, fields);
        EmitFieldNotEmptyValidation(sb, fields);

        // Failures raise ConvertException. [FieldValueDiscarded] fields are never converted.
        sb.AppendLine();
        for (int i = 0; i < fields.Length; i++)
        {
            if (fields[i].IsValueDiscarded) continue;
            EmitFieldConversion(sb, fields[i], i, plans[i]);
        }

        return hasQuotedField;
    }

    private static void EmitQuotedFinally(StringBuilder sb, EquatableArray<FieldModel> fields)
    {
        sb.AppendLine("        }");
        sb.AppendLine("        finally");
        sb.AppendLine("        {");
        for (int i = 0; i < fields.Length; i++)
        {
            if (!fields[i].IsQuoted) continue;
            sb.AppendLine($"            if (__qRent{i} is not null)");
            sb.AppendLine($"                global::System.Buffers.ArrayPool<char>.Shared.Return(__qRent{i});");
        }
        sb.AppendLine("        }");
    }

    private static void EmitParseBody(StringBuilder sb, RecordModel model, string fqType, ConverterPlan?[] plans)
    {
        sb.AppendLine($"    public {fqType} Parse(global::System.ReadOnlySpan<char> lines, int lineCount)");
        sb.AppendLine("    {");

        if (model.Fields.Length == 0)
        {
            EmitConstruction(sb, model, fqType);
            sb.AppendLine("    }");
            return;
        }

        bool hasQuoted = EmitParsePrologue(sb, model, plans);
        sb.AppendLine();
        EmitConstruction(sb, model, fqType);
        if (hasQuoted)
            EmitQuotedFinally(sb, model.Fields);
        sb.AppendLine("    }");
    }

    /// <summary>Same extraction as Parse, but assigns into an existing instance (record recycling).</summary>
    private static void EmitParseIntoBody(StringBuilder sb, RecordModel model, string fqType, ConverterPlan?[] plans)
    {
        sb.AppendLine($"    public void ParseInto(global::System.ReadOnlySpan<char> lines, int lineCount, {fqType} existing)");
        sb.AppendLine("    {");
        var fields = model.Fields;
        if (fields.Length > 0)
        {
            bool hasQuoted = EmitParsePrologue(sb, model, plans);
            sb.AppendLine();
            for (int i = 0; i < fields.Length; i++)
            {
                if (fields[i].IsValueDiscarded) continue; // [FieldValueDiscarded]: read, never stored
                sb.AppendLine($"        existing.{fields[i].Identifier} = __v{i};");
            }
            if (hasQuoted)
                EmitQuotedFinally(sb, fields);
        }
        sb.AppendLine("    }");
    }

    /// <summary>
    /// Constructs the record. Constructor arguments are emitted in PARAMETER order as named
    /// arguments (bound by parameter name, never by column position); members that are not bound to the
    /// constructor are set through an object initializer. Discarded members are never assigned.
    /// </summary>
    private static void EmitConstruction(StringBuilder sb, RecordModel model, string fqType)
    {
        var fields = model.Fields;
        var initializers = new List<string>();
        for (int i = 0; i < fields.Length; i++)
        {
            var f = fields[i];
            if (f.IsValueDiscarded) continue;
            if (f.Assign is FieldAssignKind.Setter or FieldAssignKind.Init)
                initializers.Add($"{f.Identifier} = __v{i}");
        }

        // Required members that the setters above do not cover (CS9035).
        foreach (var required in model.RequiredInits)
            initializers.Add($"{required.Identifier} = {(required.FieldIndex >= 0 ? $"__v{required.FieldIndex}" : "default!")}");

        string ctor;
        if (model.UseConstructor)
        {
            var args = new StringBuilder();
            foreach (var arg in model.ConstructorArgs)
            {
                if (args.Length > 0) args.Append(", ");
                args.Append(arg.ParameterIdentifier).Append(": ");
                args.Append(arg.FieldIndex >= 0 ? $"__v{arg.FieldIndex}" : arg.DefaultExpression ?? "default!");
            }
            ctor = $"new {fqType}({args})";
        }
        else
        {
            ctor = $"new {fqType}";
        }

        if (initializers.Count == 0)
        {
            sb.AppendLine(model.UseConstructor ? $"        return {ctor};" : $"        return {ctor}();");
            return;
        }

        sb.AppendLine($"        return {ctor}");
        sb.AppendLine("        {");
        for (int i = 0; i < initializers.Count; i++)
            sb.AppendLine($"            {initializers[i]}{(i < initializers.Count - 1 ? "," : string.Empty)}");
        sb.AppendLine("        };");
    }

    /// <summary>
    /// Emits the conversion of one field into the local <c>__v{i}</c>. Empty / whitespace input for converted fields follows the
    /// FileHelpers 3.x null-value rules (<see cref="GetEmptyFieldStatement"/>); every other failure raises
    /// <c>ConvertException</c> — never a silent default.
    /// </summary>
    private static void EmitFieldConversion(StringBuilder sb, FieldModel field, int i, ConverterPlan? plan)
    {
        string fieldVar = $"__f{i}";
        string target = $"__v{i}";
        string typeOfExpr = $"typeof({field.UnderlyingTypeName})";
        string nameLit = Literal(field.Name);

        if (plan is null)
        {
            // string: no conversion, no failure mode.
            sb.AppendLine($"        {field.FullTypeName} {target} = new string({fieldVar});");
            return;
        }

        sb.AppendLine($"        {field.FullTypeName} {target};");

        string emptyStatement = GetEmptyFieldStatement(field, i, target);

        if (plan.Origin == ConverterOrigin.BuiltIn && IsNumericKind(field.ValueKind))
        {
            // Numeric converters never accept blank input, so parsing first and checking for blanks only
            // on failure is equivalent — and keeps the common path to a single scan of the field.
            sb.AppendLine($"        if ({plan.Expression}.TryParse({fieldVar}, out {plan.ValueType} __p{i}))");
            sb.AppendLine($"            {target} = __p{i};");
            sb.AppendLine($"        else if ({Memory}IsWhiteSpace({fieldVar}))");
            sb.AppendLine($"            {emptyStatement}");
            sb.AppendLine("        else");
            sb.AppendLine($"            throw __ConvertError(lines, {fieldVar}, {typeOfExpr}, {nameLit}, null, null);");
            return;
        }

        if (plan.Origin == ConverterOrigin.BuiltIn)
        {
            sb.AppendLine($"        if ({Memory}IsWhiteSpace({fieldVar}))");
            sb.AppendLine($"            {emptyStatement}");
            sb.AppendLine($"        else if ({plan.Expression}.TryParse({fieldVar}, out {plan.ValueType} __p{i}))");
            sb.AppendLine($"            {target} = __p{i};");
            sb.AppendLine("        else");
            sb.AppendLine($"            throw __ConvertError(lines, {fieldVar}, {typeOfExpr}, {nameLit}, null, null);");
            return;
        }

        // Custom converters (3.x): a ConverterBase only sees empty input when it opts into
        // CustomNullHandling; a direct ISpanConverter<T> sees it unless [FieldNullValue] is present
        // or it converts the underlying T of a T? field, where empty reads as null.
        // Their exceptions are wrapped into ConvertException with the field context.
        string? emptyCondition = plan.Origin == ConverterOrigin.ConverterBase
            ? $"{Memory}IsWhiteSpace({fieldVar}) && !{plan.Expression}.CustomNullHandling"
            : field.NullValueExpression is not null || plan.UnwrapNullable ? $"{Memory}IsWhiteSpace({fieldVar})" : null;
        string converterName = SimpleTypeName(field.ConverterTypeName ?? string.Empty);
        string pad = emptyCondition is null ? string.Empty : "    ";
        if (emptyCondition is not null)
        {
            sb.AppendLine($"        if ({emptyCondition})");
            sb.AppendLine($"            {emptyStatement}");
            sb.AppendLine("        else");
            sb.AppendLine("        {");
        }

        string outTarget = plan.UnwrapNullable ? $"{plan.ValueType} __p{i}" : target;
        sb.AppendLine($"{pad}        bool __ok{i};");
        sb.AppendLine($"{pad}        try");
        sb.AppendLine($"{pad}        {{");
        sb.AppendLine($"{pad}            __ok{i} = {plan.Expression}.TryParse({fieldVar}, out {outTarget});");
        if (plan.UnwrapNullable)
            sb.AppendLine($"{pad}            {target} = __p{i};");
        sb.AppendLine($"{pad}        }}");
        sb.AppendLine($"{pad}        catch (global::System.Exception __ex{i}) when (__ex{i} is not global::ModernLibs.FileHelpers.BadUsageException)");
        sb.AppendLine($"{pad}        {{");
        sb.AppendLine($"{pad}            throw __ConverterFailure(lines, {fieldVar}, {typeOfExpr}, {nameLit}, {Literal(converterName)}, __ex{i});");
        sb.AppendLine($"{pad}        }}");
        sb.AppendLine($"{pad}        if (!__ok{i})");
        sb.AppendLine($"{pad}            throw __ConvertError(lines, {fieldVar}, {typeOfExpr}, {nameLit}, null, null);");
        if (emptyCondition is not null)
            sb.AppendLine("        }");
    }

    private static bool IsNumericKind(FieldValueKind kind) => kind is
        FieldValueKind.Byte or FieldValueKind.SByte or FieldValueKind.Int16 or FieldValueKind.UInt16 or
        FieldValueKind.Int32 or FieldValueKind.UInt32 or FieldValueKind.Int64 or FieldValueKind.UInt64 or
        FieldValueKind.Decimal or FieldValueKind.Double or FieldValueKind.Single;

    /// <summary>
    /// Statement executed when a converted field is empty or whitespace-only (FileHelpers 3.x
    /// <c>GetNullValue</c>): the <c>[FieldNullValue]</c> value when present, otherwise <c>T?</c>
    /// reads as null, a non-nullable value type raises <c>NullValueNotFoundException</c>, and a reference
    /// type reads as null.
    /// </summary>
    private static string GetEmptyFieldStatement(FieldModel field, int fieldIdx, string target)
    {
        if (field.NullValueExpression is not null)
            return $"{target} = {field.NullValueExpression};";
        if (field.IsNullableValueType)
            return $"{target} = null;";
        if (!field.IsValueType)
            return $"{target} = default!;";
        return $"throw __NullValueNotFound(lines, __f{fieldIdx}, {Literal(field.Name)});";
    }

    /// <summary>
    /// Splits a multi-line ([FieldInNewLine]) record into <c>__line0</c> .. <c>__lineN</c>. A line with a
    /// <c>[FieldQuoted]</c> delimited field ends at the first line break outside its quoted values (3.x continues
    /// a multiline quoted value on the next physical line); other lines end at the first line break.
    /// </summary>
    private static void EmitMultiLineSplitting(StringBuilder sb, RecordModel model, int lineCount)
    {
        var fields = model.Fields;
        bool delimited = string.Equals(model.RecordKind, "Delimited", StringComparison.Ordinal);

        // Field range of each line: line 0 holds the fields before the first [FieldInNewLine] field (none when
        // the first field is on a new line); every [FieldInNewLine] field starts the next line.
        var lineStart = new int[lineCount];
        var lineFieldCount = new int[lineCount];
        var lineQuoted = new bool[lineCount];
        int line = 0;
        for (int f = 0; f < fields.Length; f++)
        {
            if (fields[f].IsInNewLine)
            {
                line++;
                lineStart[line] = f;
            }

            lineFieldCount[line]++;
            lineQuoted[line] |= delimited && fields[f].IsQuoted;
        }

        sb.AppendLine("        // Split the multi-line record into its physical lines.");
        sb.AppendLine("        var __remaining = lines;");
        for (int i = 0; i < lineCount; i++)
        {
            if (lineQuoted[i])
                sb.AppendLine($"        int __nl{i} = global::ModernLibs.FileHelpers.RecordParsing.IndexOfLineBreak(__remaining, new global::System.ReadOnlySpan<global::ModernLibs.FileHelpers.FieldDescriptor>(_fields, {lineStart[i]}, {lineFieldCount[i]}), {Literal(model.Delimiter)});");
            else
                sb.AppendLine($"        int __nl{i} = {Memory}IndexOfAny(__remaining, '\\r', '\\n');");
            sb.AppendLine($"        var __line{i} = __nl{i} >= 0 ? __remaining.Slice(0, __nl{i}) : __remaining;");
            if (i < lineCount - 1)
            {
                sb.AppendLine($"        if (__nl{i} >= 0)");
                sb.AppendLine("        {");
                sb.AppendLine($"            __remaining = __remaining.Slice(__nl{i} + 1);");
                sb.AppendLine("            if (__remaining.Length > 0 && __remaining[0] == '\\n')");
                sb.AppendLine("                __remaining = __remaining.Slice(1);");
                sb.AppendLine("        }");
            }
        }
        sb.AppendLine();
    }

    /// <summary>
    /// The first field is on a new line: as in 3.x, the record's first physical line holds no field and must be
    /// blank (whitespace only); the first field is read from the next line.
    /// </summary>
    private static void EmitBlankFirstLineValidation(StringBuilder sb, FieldModel firstField)
    {
        sb.AppendLine($"        // Field '{firstField.Name}' is on a new line: the record's first line must be blank (3.x).");
        sb.AppendLine($"        if (!{Memory}IsWhiteSpace(__line0))");
        sb.AppendLine($"            throw new global::ModernLibs.FileHelpers.BadUsageException(\"Text '\" + __line0.ToString() + {Literal($"' found before the new line of the field: {firstField.Name} (this is not allowed when you use [FieldInNewLine]).")});");
        sb.AppendLine();
    }

    /// <summary>
    /// Sequential IndexOf + slice splitting for delimited records (fully inlined). Missing trailing
    /// fields read as empty, which is what <c>[FieldOptional]</c> needs.
    /// A quote-aware scanner is used when any field is <c>[FieldQuoted]</c>.
    /// The boundary after field i is field i's own [FieldDelimiter] or the record delimiter (FileHelpers 3.x:
    /// the override is the delimiter that follows the field).
    /// </summary>
    private static void EmitDelimitedFieldSplitting(StringBuilder sb, RecordModel model, bool hasMultiLine)
    {
        var fields = model.Fields;
        if (HasAnyQuotedField(fields))
        {
            EmitQuoteAwareDelimitedSplitting(sb, model, hasMultiLine);
            return;
        }

        string recordDelim = model.Delimiter;
        int currentLine = 0;
        string currentLineVar = hasMultiLine ? "__line0" : "line";
        int fieldCount = fields.Length;

        for (int i = 0; i < fieldCount; i++)
        {
            var field = fields[i];
            if (hasMultiLine && field.IsInNewLine)
            {
                currentLine++;
                currentLineVar = $"__line{currentLine}";
                sb.AppendLine($"        // Field '{field.Name}' starts physical line {currentLine}");
            }

            string delim = field.Delimiter ?? recordDelim;
            string delimArgs = delim.Length == 1
                ? CharLiteral(delim[0])
                : $"{Literal(delim)}, global::System.StringComparison.Ordinal";

            bool isLastOnThisLine = i == fieldCount - 1 || (hasMultiLine && fields[i + 1].IsInNewLine);
            string srcSpan = i == 0 || (hasMultiLine && field.IsInNewLine) ? currentLineVar : $"__rem{i}";

            if (isLastOnThisLine)
            {
                sb.AppendLine($"        var __f{i} = {srcSpan};");
            }
            else
            {
                sb.AppendLine($"        int __sep{i} = {Memory}IndexOf({srcSpan}, {delimArgs});");
                sb.AppendLine($"        var __f{i} = __sep{i} >= 0 ? {srcSpan}.Slice(0, __sep{i}) : {srcSpan};");
                sb.AppendLine($"        var __rem{i + 1} = __sep{i} >= 0 ? {srcSpan}.Slice(__sep{i} + {delim.Length}) : global::System.ReadOnlySpan<char>.Empty;");
            }
        }
    }

    /// <summary>
    /// The record's quote char: FileHelpers 3.x uses one quote char per record, the first
    /// <c>[FieldQuoted]</c> field's char is canonical. Null when no field is quoted.
    /// </summary>
    private static char? RecordQuoteChar(EquatableArray<FieldModel> fields)
    {
        foreach (var f in fields)
        {
            if (f.IsQuoted) return f.QuoteChar;
        }
        return null;
    }

    /// <summary>
    /// Quote-aware splitting with the engine's rule (<c>QuoteBalanceScanner</c>): a quote opens a
    /// quoted section only at field start (after spaces/tabs only when the field's [FieldTrim] trims the
    /// start, as in 3.x), using the record quote char. Inside,
    /// doubled quotes are escapes; after the closing quote everything up to the next delimiter belongs to the
    /// field. A quote elsewhere (<c>5" ruler</c>) is literal. Raw spans are kept;
    /// <see cref="EmitFieldQuotedStripPass"/> removes the quotes and unescapes.
    /// </summary>
    private static void EmitQuoteAwareDelimitedSplitting(StringBuilder sb, RecordModel model, bool hasMultiLine)
    {
        var fields = model.Fields;
        int fieldCount = fields.Length;
        string recordDelim = model.Delimiter;
        const string Bad = "global::ModernLibs.FileHelpers.BadUsageException";

        sb.AppendLine("        // Quote-aware delimited splitting (3.x DelimitedField rules; quotes only in [FieldQuoted] fields).");
        int currentLine = 0;
        for (int i = 0; i < fieldCount; i++)
        {
            var field = fields[i];
            bool lineStart = i == 0 || (hasMultiLine && field.IsInNewLine);
            if (hasMultiLine && field.IsInNewLine)
            {
                currentLine++;
                sb.AppendLine($"        // Field '{field.Name}' starts physical line {currentLine}");
            }

            string currentLineVar = hasMultiLine ? $"__line{currentLine}" : "line";
            string src = lineStart ? currentLineVar : $"__qrem{i}";
            string delim = field.Delimiter ?? recordDelim;
            bool isLastOnThisLine = i == fieldCount - 1 || (hasMultiLine && fields[i + 1].IsInNewLine);
            string delimArgs = delim.Length == 1
                ? CharLiteral(delim[0])
                : $"{Literal(delim)}, global::System.StringComparison.Ordinal";
            string atDelimiter = delim.Length == 1
                ? $"{src}[__qsPos{i}] == {CharLiteral(delim[0])}"
                : $"{Memory}StartsWith({src}.Slice(__qsPos{i}), {Literal(delim)}, global::System.StringComparison.Ordinal)";

            sb.AppendLine($"        global::System.ReadOnlySpan<char> __f{i};");
            if (!isLastOnThisLine)
            {
                sb.AppendLine($"        global::System.ReadOnlySpan<char> __qrem{i + 1};");
                sb.AppendLine($"        bool __qhas{i + 1};");
            }

            if (!field.IsQuoted)
            {
                // Quote characters are literal text in fields without [FieldQuoted] (3.x BasicExtractString).
                EmitPlainSplit(sb, i, src, delimArgs, delim.Length, isLastOnThisLine, indent: "        ");
                continue;
            }

            string qLit = CharLiteral(field.QuoteChar);
            bool trimStart = field.TrimMode is 1 or 2;
            bool trimEnd = field.TrimMode is 1 or 3;
            bool quoteRequired = field.QuoteMode is 0 or 2; // AlwaysQuoted, OptionalForWrite
            string q = field.QuoteChar.ToString();

            sb.AppendLine($"        bool __fq{i} = false;");
            sb.AppendLine($"        int __qsPos{i} = 0;");
            sb.AppendLine($"        int __qsLen{i} = {src}.Length;");
            bool hasTrimChars = !string.IsNullOrEmpty(field.TrimChars);
            if (trimStart && hasTrimChars)
            {
                // 3.x: the [FieldTrim] chars before the opening quote are skipped only when the field trims its start.
                sb.AppendLine($"        while (__qsPos{i} < __qsLen{i} && __trim{i}.Contains({src}[__qsPos{i}]) && !({atDelimiter}))");
                sb.AppendLine($"            __qsPos{i}++;");
            }
            sb.AppendLine($"        if (__qsPos{i} < __qsLen{i} && {src}[__qsPos{i}] == {qLit})");
            sb.AppendLine("        {");
            sb.AppendLine($"            int __qsStart{i} = __qsPos{i};");
            sb.AppendLine($"            __qsPos{i}++;");
            sb.AppendLine("            while (true)");
            sb.AppendLine("            {");
            sb.AppendLine($"                int __qsQ{i} = {Memory}IndexOf({src}.Slice(__qsPos{i}), {qLit});");
            sb.AppendLine($"                if (__qsQ{i} < 0)");
            sb.AppendLine($"                    throw new {Bad}(-1, __Column(lines, {src}), {Literal($"The field '{field.Name}' has an unclosed quoted string. Check that every opening {q} has a closing {q} (use {q}{q} for a quote inside the value) or allow multiline values in [FieldQuoted].")});");
            sb.AppendLine($"                __qsPos{i} += __qsQ{i};");
            sb.AppendLine($"                if (__qsPos{i} + 1 < __qsLen{i} && {src}[__qsPos{i} + 1] == {qLit}) {{ __qsPos{i} += 2; continue; }}");
            sb.AppendLine($"                __qsPos{i}++;");
            sb.AppendLine("                break;");
            sb.AppendLine("            }");
            sb.AppendLine($"            __f{i} = {src}.Slice(__qsStart{i}, __qsPos{i} - __qsStart{i});");
            sb.AppendLine($"            __fq{i} = true;");
            if (!isLastOnThisLine)
            {
                if (trimEnd && hasTrimChars)
                {
                    // 3.x: the [FieldTrim] chars after the closing quote are skipped when the field trims its end.
                    sb.AppendLine($"            while (__qsPos{i} < __qsLen{i} && __trim{i}.Contains({src}[__qsPos{i}]) && !({atDelimiter}))");
                    sb.AppendLine($"                __qsPos{i}++;");
                }
                sb.AppendLine($"            if (__qsPos{i} < __qsLen{i} && !({atDelimiter}))");
                sb.AppendLine($"                throw new {Bad}(-1, __Column(lines, {src}), {Literal($"The field '{field.Name}' is quoted but the quote char {q} is not just before the separator (You can use [FieldTrim] to avoid this error).")});");
                sb.AppendLine($"            __qhas{i + 1} = __qsPos{i} < __qsLen{i};");
                sb.AppendLine($"            __qrem{i + 1} = __qhas{i + 1} ? {src}.Slice(__qsPos{i} + {delim.Length}) : global::System.ReadOnlySpan<char>.Empty;");
            }
            // 3.x ignores anything after the closing quote of the last field.
            sb.AppendLine("        }");
            sb.AppendLine("        else");
            sb.AppendLine("        {");
            if (quoteRequired)
            {
                // AlwaysQuoted / OptionalForWrite: the value must be quoted (an absent optional field is empty).
                // A required field at the start of a line is always present: the throws are unconditional
                // and no unquoted extraction follows (an `if (true)` would make it unreachable, CS0162).
                bool alwaysPresent = !field.IsOptional && lineStart;
                string indent = alwaysPresent ? "            " : "                ";
                if (!alwaysPresent)
                {
                    string present = field.IsOptional ? $"!{src}.IsEmpty" : $"__qhas{i}";
                    sb.AppendLine($"            if ({present})");
                    sb.AppendLine("            {");
                }
                sb.AppendLine($"{indent}if ({Memory}StartsWith({Memory}TrimStart({src}), {Literal(q)}, global::System.StringComparison.Ordinal))");
                sb.AppendLine($"{indent}    throw new {Bad}(-1, __Column(lines, {src}), {Literal($"The field '{field.Name}' has spaces before the quote char {q}. Use [FieldTrim(TrimMode.Left)] or [FieldTrim(TrimMode.Both)] to allow them.")});");
                sb.AppendLine($"{indent}throw new {Bad}(-1, __Column(lines, {src}), {Literal($"The field '{field.Name}' does not begin with the quote char {q}. You can use [FieldQuoted(QuoteMode.OptionalForRead)] to allow unquoted values.")});");
                if (alwaysPresent)
                {
                    sb.AppendLine("        }");
                    continue;
                }
                sb.AppendLine("            }");
            }
            // 3.x trims the start (the [FieldTrim] chars) before extracting an unquoted value too.
            string plainSrc = trimStart && hasTrimChars ? $"{src}.Slice(__qsPos{i})" : src;
            EmitPlainSplit(sb, i, plainSrc, delimArgs, delim.Length, isLastOnThisLine, indent: "            ");
            sb.AppendLine("        }");
        }
    }

    /// <summary>
    /// Cached <c>SearchValues</c> of the [FieldTrim] characters of quoted delimited fields, used to skip them
    /// around the quotes (allocation-free per record).
    /// </summary>
    private static void EmitTrimCharSets(StringBuilder sb, RecordModel model)
    {
        if (!string.Equals(model.RecordKind, "Delimited", StringComparison.Ordinal)) return;
        bool any = false;
        for (int i = 0; i < model.Fields.Length; i++)
        {
            var f = model.Fields[i];
            if (!f.IsQuoted || f.TrimMode is not (1 or 2 or 3) || string.IsNullOrEmpty(f.TrimChars)) continue;
            sb.AppendLine($"    private static readonly global::System.Buffers.SearchValues<char> __trim{i} = global::System.Buffers.SearchValues.Create({UnicodeLiteral(f.TrimChars!)});");
            any = true;
        }
        if (any) sb.AppendLine();
    }

    /// <summary>String literal with every non-ASCII or control character written as <c>\uXXXX</c>.</summary>
    private static string UnicodeLiteral(string value)
    {
        var sb = new StringBuilder("\"");
        foreach (char c in value)
        {
            if (c is '"' or '\\') sb.Append('\\').Append(c);
            else if (c < ' ' || c > '~') sb.Append("\\u").Append(((int)c).ToString("X4", System.Globalization.CultureInfo.InvariantCulture));
            else sb.Append(c);
        }
        return sb.Append('"').ToString();
    }

    /// <summary>Splits field <paramref name="i"/> at the next delimiter (no quote handling).</summary>
    private static void EmitPlainSplit(StringBuilder sb, int i, string src, string delimArgs, int delimLength, bool isLastOnThisLine, string indent)
    {
        if (isLastOnThisLine)
        {
            sb.AppendLine($"{indent}__f{i} = {src};");
            return;
        }

        sb.AppendLine($"{indent}int __qsSep{i} = {Memory}IndexOf({src}, {delimArgs});");
        sb.AppendLine($"{indent}__f{i} = __qsSep{i} < 0 ? {src} : {src}.Slice(0, __qsSep{i});");
        sb.AppendLine($"{indent}__qhas{i + 1} = __qsSep{i} >= 0;");
        sb.AppendLine($"{indent}__qrem{i + 1} = __qsSep{i} < 0 ? global::System.ReadOnlySpan<char>.Empty : {src}.Slice(__qsSep{i} + {delimLength});");
    }

    /// <summary>
    /// Fixed-length line width validation per <c>FixedMode</c>. A line may end exactly where a
    /// trailing <c>[FieldOptional]</c> field starts (single-line records).
    /// </summary>
    private static void EmitFixedLengthModeValidation(StringBuilder sb, EquatableArray<FieldModel> fields, string? fixedMode, bool hasMultiLine)
    {
        string mode = fixedMode ?? "ExactLength";
        if (string.Equals(mode, "AllowVariableLength", StringComparison.Ordinal))
            return;

        int fieldCount = fields.Length;
        int currentLine = 0;
        // One more slot than fields: when the first field is on a new line, line 0 has no fields.
        int[] widthsByLine = new int[fieldCount + 1];
        var optionalBoundaries = new List<int>();
        int running = 0;
        for (int i = 0; i < fieldCount; i++)
        {
            if (hasMultiLine && fields[i].IsInNewLine)
                currentLine++;
            if (!hasMultiLine && fields[i].IsOptional)
                optionalBoundaries.Add(running);
            if (fields[i].FixedLength > 0)
            {
                widthsByLine[currentLine] += fields[i].FixedLength;
                running += fields[i].FixedLength;
            }
        }

        // A blank first line (first field on a new line) is checked by EmitBlankFirstLineValidation.
        int firstLineIndex = hasMultiLine && fields[0].IsInNewLine ? 1 : 0;
        for (int lineIndex = firstLineIndex; lineIndex <= currentLine; lineIndex++)
        {
            string lineVar = hasMultiLine ? $"__line{lineIndex}" : "line";
            int expectedWidth = widthsByLine[lineIndex];
            int minimumWidth = optionalBoundaries.Count > 0 ? optionalBoundaries[0] : expectedWidth;
            string condition;
            switch (mode)
            {
                case "AllowMoreChars":
                    condition = $"{lineVar}.Length < {minimumWidth}";
                    break;
                case "AllowLessChars":
                    condition = $"{lineVar}.Length > {expectedWidth}";
                    break;
                default:
                    var parts = new StringBuilder($"{lineVar}.Length != {expectedWidth}");
                    foreach (int boundary in optionalBoundaries)
                        parts.Append($" && {lineVar}.Length != {boundary}");
                    condition = parts.ToString();
                    break;
            }

            string expectation = mode switch
            {
                "AllowMoreChars" => $"at least {minimumWidth} characters",
                "AllowLessChars" => $"at most {expectedWidth} characters",
                _ => $"{expectedWidth} characters",
            };
            sb.AppendLine($"        if ({condition})");
            sb.AppendLine($"            throw new global::ModernLibs.FileHelpers.BadUsageException($\"Fixed-length record line {lineIndex + 1} has length {{{lineVar}.Length}} but expected {expectation}.\");");
        }

        sb.AppendLine();
    }

    /// <summary>
    /// Raw slice arithmetic for fixed-length records. Short lines yield empty / partial slices,
    /// so missing trailing optional fields read as empty.
    /// </summary>
    private static void EmitFixedLengthFieldSplitting(StringBuilder sb, EquatableArray<FieldModel> fields, bool hasMultiLine)
    {
        int currentLine = 0;
        string currentLineVar = hasMultiLine ? "__line0" : "line";
        int runningOffset = 0;
        for (int i = 0; i < fields.Length; i++)
        {
            var field = fields[i];
            if (hasMultiLine && field.IsInNewLine)
            {
                currentLine++;
                currentLineVar = $"__line{currentLine}";
                runningOffset = 0;
                sb.AppendLine($"        // Field '{field.Name}' starts physical line {currentLine}");
            }

            int offset = runningOffset;
            int width = field.FixedLength > 0 ? field.FixedLength : 0;
            sb.AppendLine($"        var __f{i} = {currentLineVar}.Length > {offset} ? {currentLineVar}.Slice({offset}, global::System.Math.Min({width}, {currentLineVar}.Length - {offset})) : global::System.ReadOnlySpan<char>.Empty;");
            if (field.FixedLength > 0) runningOffset += field.FixedLength;
        }
    }

    /// <summary>Strips the outer quote wrapper and unescapes doubled quotes (pooled buffer when needed).</summary>
    private static void EmitFieldQuotedStripPass(StringBuilder sb, EquatableArray<FieldModel> fields, bool isDelimited)
    {
        for (int i = 0; i < fields.Length; i++)
        {
            var field = fields[i];
            if (!field.IsQuoted) continue;

            string qLit = CharLiteral(field.QuoteChar);
            sb.AppendLine();
            sb.AppendLine($"        // [FieldQuoted] strip + unescape for field '{field.Name}'.");
            sb.AppendLine(isDelimited
                ? $"        if (__fq{i})"
                : $"        if (__f{i}.Length >= 2 && __f{i}[0] == {qLit} && __f{i}[__f{i}.Length - 1] == {qLit})");
            sb.AppendLine("        {");
            sb.AppendLine($"            var __qInner{i} = __f{i}.Slice(1, __f{i}.Length - 2);");
            sb.AppendLine($"            bool __hasDoubled{i} = false;");
            sb.AppendLine($"            for (int __si{i} = 0; __si{i} < __qInner{i}.Length - 1; __si{i}++)");
            sb.AppendLine("            {");
            sb.AppendLine($"                if (__qInner{i}[__si{i}] == {qLit} && __qInner{i}[__si{i} + 1] == {qLit})");
            sb.AppendLine("                {");
            sb.AppendLine($"                    __hasDoubled{i} = true;");
            sb.AppendLine("                    break;");
            sb.AppendLine("                }");
            sb.AppendLine("            }");
            sb.AppendLine($"            if (!__hasDoubled{i})");
            sb.AppendLine("            {");
            sb.AppendLine($"                __f{i} = __qInner{i};");
            sb.AppendLine("            }");
            sb.AppendLine("            else");
            sb.AppendLine("            {");
            sb.AppendLine("                // Rented buffer, returned in the finally block after the value is materialised.");
            sb.AppendLine($"                var __qBuf{i} = global::System.Buffers.ArrayPool<char>.Shared.Rent(__qInner{i}.Length);");
            sb.AppendLine($"                __qRent{i} = __qBuf{i};");
            sb.AppendLine($"                int __qLen{i} = 0;");
            sb.AppendLine($"                for (int __qi{i} = 0; __qi{i} < __qInner{i}.Length; __qi{i}++)");
            sb.AppendLine("                {");
            sb.AppendLine($"                    char __qc{i} = __qInner{i}[__qi{i}];");
            sb.AppendLine($"                    if (__qc{i} == {qLit} && __qi{i} + 1 < __qInner{i}.Length && __qInner{i}[__qi{i} + 1] == {qLit})");
            sb.AppendLine("                    {");
            sb.AppendLine($"                        __qBuf{i}[__qLen{i}++] = {qLit};");
            sb.AppendLine($"                        __qi{i}++;");
            sb.AppendLine("                    }");
            sb.AppendLine("                    else");
            sb.AppendLine("                    {");
            sb.AppendLine($"                        __qBuf{i}[__qLen{i}++] = __qc{i};");
            sb.AppendLine("                    }");
            sb.AppendLine("                }");
            sb.AppendLine($"                __f{i} = new global::System.ReadOnlySpan<char>(__qBuf{i}, 0, __qLen{i});");
            sb.AppendLine("            }");
            sb.AppendLine("        }");
        }
    }

    /// <summary>[FieldTrim] — TrimMode 1=Both, 2=Left, 3=Right.</summary>
    private static void EmitFieldTrimPass(StringBuilder sb, EquatableArray<FieldModel> fields, bool quotedOnly = false)
    {
        for (int i = 0; i < fields.Length; i++)
        {
            if (quotedOnly && !fields[i].IsQuoted) continue;
            string method = fields[i].TrimMode switch
            {
                1 => "Trim",
                2 => "TrimStart",
                3 => "TrimEnd",
                _ => string.Empty,
            };
            if (method.Length == 0) continue;
            sb.AppendLine($"        __f{i} = {Memory}{method}(__f{i}); // [FieldTrim]");
        }
    }

    /// <summary>[FieldNotEmpty] after trim; a violation is a ConvertException (3.x).</summary>
    private static void EmitFieldNotEmptyValidation(StringBuilder sb, EquatableArray<FieldModel> fields)
    {
        for (int i = 0; i < fields.Length; i++)
        {
            var field = fields[i];
            if (!field.IsNotEmpty || field.IsValueDiscarded) continue;

            sb.AppendLine();
            sb.AppendLine($"        // [FieldNotEmpty] validation for field '{field.Name}'.");
            sb.AppendLine($"        if (__f{i}.IsEmpty || {Memory}IsWhiteSpace(__f{i}))");
            sb.AppendLine("        {");
            sb.AppendLine($"            throw __ConvertError(lines, __f{i}, typeof({field.UnderlyingTypeName}), {Literal(field.Name)}, \"The value is empty and must be populated.\", null);");
            sb.AppendLine("        }");
        }
    }

    /// <summary>
    /// Helpers that raise <c>ConvertException</c> / <c>NullValueNotFoundException</c> from parse bodies.
    /// <c>__Column</c> gives the 1-based column of a field from its offset inside the record span (-1 when the
    /// value is not part of it, for example an unescaped copy). An empty value has no characters to overlap, so
    /// its position is compared directly; the engines use the column to find the physical line of a field in
    /// a multi-line record.
    /// </summary>
    private static void EmitConversionErrorHelpers(StringBuilder sb, RecordModel model)
    {
        sb.AppendLine("    private static int __Column(global::System.ReadOnlySpan<char> lines, global::System.ReadOnlySpan<char> value)");
        sb.AppendLine("    {");
        sb.AppendLine($"        if ({Memory}Overlaps(lines, value, out int offset))");
        sb.AppendLine("            return offset + 1;");
        sb.AppendLine("        if (!value.IsEmpty)");
        sb.AppendLine("            return -1;");
        sb.AppendLine("        nint bytes = global::System.Runtime.CompilerServices.Unsafe.ByteOffset(");
        sb.AppendLine("            ref global::System.Runtime.InteropServices.MemoryMarshal.GetReference(lines),");
        sb.AppendLine("            ref global::System.Runtime.InteropServices.MemoryMarshal.GetReference(value));");
        sb.AppendLine("        return bytes >= 0 && bytes <= (nint)lines.Length * sizeof(char) ? (int)(bytes / sizeof(char)) + 1 : -1;");
        sb.AppendLine("    }");
        sb.AppendLine();
        sb.AppendLine("    private static global::ModernLibs.FileHelpers.ConvertException __ConvertError(global::System.ReadOnlySpan<char> lines, global::System.ReadOnlySpan<char> value, global::System.Type type, string field, string? extra, global::System.Exception? inner) =>");
        sb.AppendLine("        new(new string(value), type, field, -1, __Column(lines, value), extra, inner);");
        sb.AppendLine();
        sb.AppendLine("    private static global::ModernLibs.FileHelpers.NullValueNotFoundException __NullValueNotFound(global::System.ReadOnlySpan<char> lines, global::System.ReadOnlySpan<char> value, string field) =>");
        sb.AppendLine($"        new(-1, __Column(lines, value), \"No value found for the value type field: '\" + field + \"' Class: '{EscapeString(model.TypeName)}'. You must use the [FieldNullValue] attribute because this is a value type and can't be null or use a Nullable Type instead of the current type.\");");
        sb.AppendLine();

        bool hasCustomConverter = false;
        foreach (var field in model.Fields)
        {
            if (field.ConverterKind == GeneratorConverterKind.None && field.ConverterTypeName is not null)
            {
                hasCustomConverter = true;
                break;
            }
        }
        if (!hasCustomConverter) return;

        sb.AppendLine("    private static global::ModernLibs.FileHelpers.ConvertException __ConverterFailure(global::System.ReadOnlySpan<char> lines, global::System.ReadOnlySpan<char> value, global::System.Type type, string field, string converter, global::System.Exception ex)");
        sb.AppendLine("    {");
        sb.AppendLine("        if (ex is global::ModernLibs.FileHelpers.ConvertException convert)");
        sb.AppendLine("            return __ConvertError(lines, value, type, field, convert.MessageExtra, convert);");
        sb.AppendLine("        return __ConvertError(lines, value, type, field, \"Your custom converter: \" + converter + \" throws an \" + ex.GetType().Name + \" with the message: \" + ex.Message, ex);");
        sb.AppendLine("    }");
        sb.AppendLine();
    }

