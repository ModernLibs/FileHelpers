        Method(typeof(IRecyclableDescriptor<Rec>), "ParseInto", typeof(void), SpanOfChar, typeof(int), typeof(Rec)),

        // FileHelperRegistry<T>.SetDescriptor (Emitter:113-114). Closed by reflection: MLFH001 flags
        // FileHelperRegistry<Rec> written in source because Rec has no record attribute.
        Method(typeof(FileHelperRegistry<>).MakeGenericType(typeof(Rec)), "SetDescriptor", typeof(void), typeof(IRecordDescriptor<Rec>)),

        // FieldDescriptor constructor with 14 positional arguments (Emitter:169)
        Ctor(typeof(FieldDescriptor),
