// MA0051: the emitter builds one source file per record; several methods are long because they
// emit distinct, sequential code sections. Splitting further would only thread more parameters.
#pragma warning disable MA0051

using System.Text;
using Microsoft.CodeAnalysis;
using ModernLibs.FileHelpers.Generator.Models;

namespace ModernLibs.FileHelpers.Generator.Emission;

/// <summary>
/// Emits the file-scoped descriptor class and module-initializer registration class for a single
/// <see cref="RecordModel"/>. Both classes are emitted into a single source file.
/// </summary>
/// <remarks>
/// Every API used by the generated code is fully qualified (<c>global::System.MemoryExtensions.IndexOf(...)</c>
/// instead of extension-method syntax), so the output compiles in projects with <c>ImplicitUsings</c> disabled.
/// </remarks>
internal static class DescriptorEmitter
{
    private const string Converters = "global::ModernLibs.FileHelpers.Converters.";
    private const string Memory = "global::System.MemoryExtensions.";
    private const string ConverterHolder = "__Conv";

    internal static void Emit(SourceProductionContext spc, RecordModel model)
    {
        string sourceText = Generate(model);

        // Hint name is deterministic and unique per type: full metadata name + record kind.
        spc.AddSource(model.HintName, Microsoft.CodeAnalysis.Text.SourceText.From(sourceText, Encoding.UTF8));
    }

    internal static string Generate(RecordModel model)
    {
        var sb = new StringBuilder();

        // CA2255: [ModuleInitializer] in source-generated consumer code is intentional.
        // CS0612/CS0618: record members may be [Obsolete]; generated accessors must not warn.
        sb.AppendLine("// <auto-generated/>");
        sb.AppendLine("#nullable enable");
        sb.AppendLine("#pragma warning disable CA2255 // ModuleInitializer in source-generated consumer code");
        sb.AppendLine("#pragma warning disable CS0612, CS0618 // obsolete record members");
        sb.AppendLine();

        if (!string.IsNullOrEmpty(model.Namespace))
        {
            sb.AppendLine($"namespace {model.Namespace};");
            sb.AppendLine();
        }

        // Fully-qualified, containing-type-aware, keyword-escaped type reference.
        string fqType = model.FullyQualifiedName;
        var fields = model.Fields;
        bool isReferenceType = model.TypeKind.IndexOf("struct", StringComparison.Ordinal) < 0;

        // IRecyclableDescriptor<T> (ParseInto) needs every stored member to have a regular setter.
        bool supportsParseInto = isReferenceType && !model.UseConstructor && AllStoredFieldsSettable(fields);

        string implements = supportsParseInto
            ? $" : global::ModernLibs.FileHelpers.IRecyclableDescriptor<{fqType}>"
            : $" : global::ModernLibs.FileHelpers.IRecordDescriptor<{fqType}>";
        string descriptorName = $"__{model.TypeName}Descriptor";

        sb.AppendLine($"file sealed class {descriptorName}{implements}");
        sb.AppendLine("{");
        sb.AppendLine($"    public static readonly {descriptorName} Instance = new();");
        sb.AppendLine();

        var plans = new ConverterPlan?[fields.Length];
        for (int i = 0; i < fields.Length; i++)
            plans[i] = GetConverterPlan(fields[i], i);
        EmitConverterHolder(sb, plans);
        EmitTrimCharSets(sb, model);

        EmitConversionErrorHelpers(sb, model);
        EmitWriteHelpers(sb);

        EmitParseBody(sb, model, fqType, plans);
        sb.AppendLine();

        if (supportsParseInto)
        {
            EmitParseIntoBody(sb, model, fqType, plans);
            sb.AppendLine();
        }

        EmitFormatBody(sb, model, fqType, plans);
        sb.AppendLine();

        sb.AppendLine("    public global::System.ReadOnlySpan<global::ModernLibs.FileHelpers.FieldDescriptor> Fields =>");
        sb.AppendLine("        new global::System.ReadOnlySpan<global::ModernLibs.FileHelpers.FieldDescriptor>(_fields);");
        sb.AppendLine();

        EmitOptionsProperty(sb, model);
        sb.AppendLine();

        // CreateDefaultInstance: the instance INotifyRead<T>.BeforeRead is called on.
        sb.AppendLine($"    public {fqType} CreateDefaultInstance()");
        sb.AppendLine("    {");
        sb.AppendLine($"        return {DefaultConstruction(model, fqType, isReferenceType)};");
        sb.AppendLine("    }");
        sb.AppendLine();

        EmitFieldDescriptors(sb, model, fqType);
        sb.AppendLine("}");
        sb.AppendLine();

        sb.AppendLine($"file static class __{model.TypeName}Registration");
        sb.AppendLine("{");
        sb.AppendLine("    [global::System.Runtime.CompilerServices.ModuleInitializer]");
        sb.AppendLine("    internal static void Register()");
        sb.AppendLine("    {");
        sb.AppendLine($"        global::ModernLibs.FileHelpers.FileHelperRegistry<{fqType}>");
        sb.AppendLine($"            .SetDescriptor({descriptorName}.Instance);");
        sb.AppendLine("    }");
        sb.AppendLine("}");

        return sb.ToString();
    }

    private static bool AllStoredFieldsSettable(EquatableArray<FieldModel> fields)
    {
        foreach (var f in fields)
        {
            if (f.IsValueDiscarded) continue;
            if (f.Assign != FieldAssignKind.Setter) return false;
        }
        return true;
    }

    /// <summary>Expression that creates an instance without parsed values (empty records, BeforeRead).</summary>
    /// <remarks>
    /// A record built through a constructor is never created with fake (<c>default!</c>) arguments, which a
    /// validating constructor would reject: an accessible parameterless constructor is used when there is one,
    /// otherwise the instance is created without running any constructor.
    /// </remarks>
    private static string DefaultConstruction(RecordModel model, string fqType, bool isReferenceType)
    {
        if (!isReferenceType) return "default";
        if (model.DefaultUninitialized)
            return $"({fqType})global::System.Runtime.CompilerServices.RuntimeHelpers.GetUninitializedObject(typeof({fqType}))";

        string construction = $"new {fqType}()";

        // Required members must be set by the object initializer (CS9035).
        if (model.DefaultRequired.Length == 0) return construction;
        var initializers = new List<string>();
        foreach (string identifier in model.DefaultRequired)
            initializers.Add(identifier + " = default!");
        return $"{construction} {{ {string.Join(", ", initializers)} }}";
    }

    private static void EmitFieldDescriptors(StringBuilder sb, RecordModel model, string fqType)
    {
        sb.AppendLine("    private static readonly global::ModernLibs.FileHelpers.FieldDescriptor[] _fields =");
        sb.AppendLine("        new global::ModernLibs.FileHelpers.FieldDescriptor[]");
        sb.AppendLine("        {");

        bool isFixed = string.Equals(model.RecordKind, "FixedLength", StringComparison.Ordinal);
        int runningOffset = 0;
        for (int i = 0; i < model.Fields.Length; i++)
        {
            var field = model.Fields[i];
            int offset = isFixed ? runningOffset : -1;
            int width = isFixed ? field.FixedLength : -1;
            string delimiterArg = field.Delimiter is not null ? Literal(field.Delimiter) : "null";
            string captionArg = field.Caption is not null ? Literal(field.Caption) : "null";
            string cultureNameArg = field.CultureName is not null ? Literal(field.CultureName) : "null";
            sb.AppendLine($"            new(nameof({fqType}.{field.Identifier}), typeof({field.FullTypeName}), {field.Order}, {offset}, {width}, {delimiterArg}, {Bool(field.IsInNewLine)}, {captionArg}, {cultureNameArg}, {Bool(field.IsOptional)}, (global::ModernLibs.FileHelpers.TrimMode){field.TrimMode ?? 0}, {CharLiteral(field.IsQuoted ? field.QuoteChar : '\0')}, (global::ModernLibs.FileHelpers.MultilineMode){field.QuoteMultiline}, {(field.TrimMode is 1 or 2 or 3 && field.TrimChars is not null ? UnicodeLiteral(field.TrimChars) : "null")}),");
            if (isFixed && field.FixedLength > 0) runningOffset += field.FixedLength;
        }

        sb.AppendLine("        };");
    }

