using TUnit.Core;

namespace ModernLibs.FileHelpers.Tests.Compat;

/// <summary>
/// A library compiled against 4.9.1 carries descriptors generated by the 4.9.1 generator (Generated49). On the
/// current runtime they must read, report errors and write exactly as they did on the 4.9.1 runtime (the golden
/// texts in Golden49) and exactly as the descriptors the current generator makes for the same record (the
/// <c>...Twin</c> types).
/// </summary>
[Category("Compat")]
public sealed class Compat49Tests
{
    [Test]
    [DisplayName("A 4.9.1 descriptor reads and writes as the current one: $name")]
    [MethodDataSource(typeof(Compat49Matrix), nameof(Compat49Matrix.All))]
    public async Task Descriptor_From_4_9_1_Matches_The_Current_One(
        string name, Func<string, string> readOld, Func<string, string> readNew,
        Func<string, string> roundTripOld, Func<string, string> roundTripNew)
    {
        string? regenerate = Compat49Golden.RegenerateDirectory;
        var golden = new List<(string Header, string Text)>();
        int index = 0;
        foreach (string input in Compat49Inputs.For(name))   // at least: valid rows, a short row, a long row,
        {                                                    // a bad value, an unclosed quote, an empty line
            string kind = Compat49Inputs.Kinds[index];
            string oldRead = readOld(input);
            string oldRoundTrip = roundTripOld(input);

            // The 4.9.1 descriptor still behaves as it did on the 4.9.1 runtime (Golden49) ...
            if (regenerate is null)
            {
                await Assert.That(oldRead).IsEqualTo(Compat49Golden.Expected(name, index, "read"))
                    .Because($"{name} input {index} ({kind}): 4.9.1 read against Golden49");
                await Assert.That(oldRoundTrip).IsEqualTo(Compat49Golden.Expected(name, index, "round-trip"))
                    .Because($"{name} input {index} ({kind}): 4.9.1 round trip against Golden49");
            }
            else
            {
                golden.Add((Compat49Golden.Header(index, "read"), oldRead));
                golden.Add((Compat49Golden.Header(index, "round-trip"), oldRoundTrip));
            }

            // ... and as the descriptor that the current generator makes.
            await Assert.That(oldRead).IsEqualTo(readNew(input))
                .Because($"{name} input {index} ({kind}): 4.9.1 read against the current descriptor");
            await Assert.That(oldRoundTrip).IsEqualTo(roundTripNew(input))
                .Because($"{name} input {index} ({kind}): 4.9.1 round trip against the current descriptor");
            index++;
        }

        if (regenerate is not null)
        {
            Compat49Golden.Write(regenerate, name, golden);
            // A regeneration run checks nothing against Golden49, so it must never report a pass.
            Fail.Test($"{name}: Golden49 file written to {regenerate} ({Compat49Golden.RegenerateVariable} is set; "
                + "the 4.9.1 read and round trip were NOT checked against Golden49). Review the git diff, then run again without the variable.");
        }
    }

    [Test]
    [DisplayName("Compat49Inputs.FieldCount is the field count of both descriptors: $name")]
    [MethodDataSource(typeof(Compat49Matrix), nameof(Compat49Matrix.FieldCounts))]
    public async Task FieldCount_Matches_Both_Descriptors(string name, int oldCount, int newCount)
    {
        await Assert.That(Compat49Inputs.FieldCount(name)).IsEqualTo(oldCount);
        await Assert.That(newCount).IsEqualTo(oldCount);
    }

    [Test]
    [DisplayName("The matrix covers the 19 record shapes, each with inputs")]
    public async Task Matrix_Covers_Every_Shape()
    {
        var names = Compat49Matrix.All().Select(c => c.Name).ToArray();

        await Assert.That(names.Length).IsEqualTo(19);
        await Assert.That(names.Distinct(StringComparer.Ordinal).Count()).IsEqualTo(19);
        foreach (string name in names)
            await Assert.That(Compat49Inputs.For(name).Count()).IsEqualTo(Compat49Inputs.Kinds.Length);
    }
}
