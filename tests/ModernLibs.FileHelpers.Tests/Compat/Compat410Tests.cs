using System.Text;
using TUnit.Core;

namespace ModernLibs.FileHelpers.Tests.Compat;

/// <summary>
/// A library compiled against 4.10.0 carries descriptors generated by the 4.10.0 generator (Generated410): the
/// tokenized read members and the record writer members of 4.10 included. On every later 4.x runtime they must read,
/// report errors and write exactly as the 4.9.1 descriptors did (the golden texts in Golden49, which 4.10.0 keeps), and
/// the default, scalar-tokenizer and legacy read paths and the record writer and legacy writer must agree on them.
/// </summary>
/// <remarks>
/// The shapes, inputs and write cases are those of <see cref="Compat49Matrix"/>: <c>Compat410X</c> is the 4.10.0
/// output for <c>Compat49XTwin</c> (<c>Generated410/README.md</c>), mapped to the shape <c>Compat49X</c> by
/// <c>ShapeName</c>.
/// </remarks>
[Category("Compat")]
public sealed class Compat410Tests
{
    /// <summary>The shapes: the 19 of Generated49 and the path-only <c>Compat49NotEmpty</c>.</summary>
    public static IEnumerable<Compat410Shape> Shapes()
    {
        yield return Shape<Compat410Plain25>();
        yield return Shape<Compat410Optional>();
        yield return Shape<Compat410PerFieldDelimiter>();
        yield return Shape<Compat410NewLine>();
        yield return Shape<Compat410Trim>();
        yield return Shape<Compat410QuoteAlways>();
        yield return Shape<Compat410QuoteOptionalRead>();
        yield return Shape<Compat410QuoteOptionalWrite>();
        yield return Shape<Compat410QuoteOptionalBoth>();
        yield return Shape<Compat410MultilineNotAllow>();
        yield return Shape<Compat410Recyclable>();
        yield return Shape<Compat410Struct>();
        yield return Shape<Compat410Ctor>();
        yield return Shape<Compat410FixedExact>();
        yield return Shape<Compat410FixedMore>();
        yield return Shape<Compat410FixedLess>();
        yield return Shape<Compat410FixedVariable>();
        yield return Shape<Compat410ConverterBase>();
        yield return Shape<Compat410SpanConverter>();
        yield return Shape<Compat410NotEmpty>();
    }

    public static IEnumerable<Func<Compat410Shape>> Cases() => Shapes().Select(s => (Func<Compat410Shape>)(() => s));

    [Test]
    [DisplayName("A 4.10.0 descriptor reads and writes as the 4.9.1 golden text: $shape")]
    [MethodDataSource(nameof(Cases))]
    public async Task Descriptor_From_4_10_0_Matches_Golden49(Compat410Shape shape)
    {
        if (!shape.HasGolden)
            return;

        int index = 0;
        foreach (string input in Compat49Inputs.For(shape.Golden))
        {
            string kind = Compat49Inputs.Kinds[index];
            await Assert.That(shape.Read(input)).IsEqualTo(Compat49Golden.Expected(shape.Golden, index, "read"))
                .Because($"{shape.Name} input {index} ({kind}): 4.10.0 read against Golden49");
            await Assert.That(shape.RoundTrip(input)).IsEqualTo(Compat49Golden.Expected(shape.Golden, index, "round-trip"))
                .Because($"{shape.Name} input {index} ({kind}): 4.10.0 round trip against Golden49");
            index++;
        }
    }

    [Test]
    [DisplayName("The default, scalar and legacy read paths agree on a 4.10.0 descriptor: $shape")]
    [MethodDataSource(nameof(Cases))]
    public async Task Read_Paths_Agree_On_The_Snapshot(Compat410Shape shape)
    {
        var inputs = Compat49Inputs.For(shape.Golden).Select((input, i) => (Kind: Compat49Inputs.Kinds[i], Input: input))
            .Concat(Compat49Inputs.PathOnly(shape.Golden).Select((input, i) => (Kind: "path-only-" + i, Input: input)));

        foreach (var (kind, input) in inputs)
        {
            string legacy = shape.ReadLegacy(input);
            await Assert.That(shape.ReadDefault(input)).IsEqualTo(legacy)
                .Because($"{shape.Name} input {kind}: default path (tokenized: {shape.Tokenized}) against the legacy path");
            await Assert.That(shape.ReadScalar(input)).IsEqualTo(legacy)
                .Because($"{shape.Name} input {kind}: scalar tokenizer against the legacy path");
        }
    }

    [Test]
    [DisplayName("The record writer and the legacy writer agree on a 4.10.0 descriptor: $shape")]
    [MethodDataSource(nameof(Cases))]
    public async Task Writers_Agree_On_The_Snapshot(Compat410Shape shape)
    {
        await Assert.That(shape.RecordWriter).IsTrue().Because($"{shape.Name}: the descriptor implements IRecordWriterDescriptor<T>");
        if (!shape.HasGolden)
            return;   // the path-only shape has no write cases

        int index = 0;
        foreach (string input in Compat49Inputs.For(shape.Golden))
        {
            foreach (string newLine in (string[])["\r\n", "\n", "|\n"])
            {
                foreach (bool events in (bool[])[false, true])
                {
                    string legacy = shape.WriteLegacy(input, newLine, events);
                    await Assert.That(shape.WriteDefault(input, newLine, events)).IsEqualTo(legacy)
                        .Because($"{shape.Name} input {index} ({Compat49Inputs.Kinds[index]}), newline {newLine.Replace("\r", "\\r", StringComparison.Ordinal).Replace("\n", "\\n", StringComparison.Ordinal)}, events {events}");
                }
            }

            index++;
        }
    }

    [Test]
    public async Task The_Snapshot_Covers_Every_Shape_And_Binds_The_4_10_Interfaces()
    {
        var shapes = Shapes().ToList();
        string[] expected = [.. Compat49Matrix.All().Select(c => c.Name), .. Compat49Matrix.PathOnlyShapes];

        await Assert.That(shapes.Count).IsEqualTo(20);
        await Assert.That(shapes.Select(s => s.Golden)).IsEquivalentTo(expected);

        // 4.10 descriptors: a delimited, one-line record is read through ITokenizedDescriptor<T>; every valid record
        // is written through IRecordWriterDescriptor<T>.
        foreach (string name in (string[])["Compat49Plain25", "Compat49QuoteAlways", "Compat49NotEmpty"])
        {
            var shape = shapes.Single(s => string.Equals(s.Golden, name, StringComparison.Ordinal));
            await Assert.That(shape.TokenizedDescriptor).IsTrue().Because(name);
            await Assert.That(shape.Tokenized).IsTrue().Because(name + ": Core.Tokenized of the default engine");
        }

        foreach (var shape in shapes)
            await Assert.That(shape.RecordWriter).IsTrue().Because(shape.Name);
    }

    private static Compat410Shape Shape<T>()
    {
        string name = typeof(T).Name;
        var descriptor = FileHelperRegistry<T>.Descriptor;
        var legacyWriter = EnginePaths.FromSwitches with { LegacyWriter = true };
        var (readDefault, readScalar, readLegacy, tokenized) =
            Compat49Matrix.PathReadsOf(descriptor, static () => new FileHelperEngine<T>());
        return new Compat410Shape(
            name,
            "Compat49" + name["Compat410".Length..],
            input => Compat49Matrix.Read(input, static () => new FileHelperEngine<T>()),
            Compat49Matrix.RoundTrip<T>,
            readDefault,
            readScalar,
            readLegacy,
            tokenized,
            (input, newLine, events) => Compat49Matrix.RoundTripWith(input, newLine, events, static () => new FileHelperEngine<T>()),
            (input, newLine, events) => Compat49Matrix.RoundTripWith(input, newLine, events, () => new FileHelperEngine<T>(descriptor, Encoding.UTF8, legacyWriter)),
            descriptor is IRecordWriterDescriptor<T>,
            descriptor is ITokenizedDescriptor<T>);
    }

    /// <summary>The reads and writes of one Generated410 shape; <c>Golden</c> is the Compat49 shape it was made from.</summary>
    public sealed record Compat410Shape(
        string Name,
        string Golden,
        Func<string, string> Read,
        Func<string, string> RoundTrip,
        Func<string, string> ReadDefault,
        Func<string, string> ReadScalar,
        Func<string, string> ReadLegacy,
        bool Tokenized,
        Func<string, string, bool, string> WriteDefault,
        Func<string, string, bool, string> WriteLegacy,
        bool RecordWriter,
        bool TokenizedDescriptor)
    {
        /// <summary>Whether Golden49 has a file for the shape (not the path-only shape).</summary>
        public bool HasGolden => !Compat49Matrix.PathOnlyShapes.Contains(Golden, StringComparer.Ordinal);

        public override string ToString() => Name;
    }
}
