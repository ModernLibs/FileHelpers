// MA0051: DescriptorEmitter.Emit is a single-responsibility string-building method.
// The length comes from emitting distinct code sections (header, namespace, descriptor class,
// parse body, format stub, fields array, registration class) — all required by the emitter contract.
// Extracting sub-methods would require passing model, sb, fqType, and TypeName as parameters
// for marginal readability gain. Suppression is intentional.
#pragma warning disable MA0051

using System.Text;
using Microsoft.CodeAnalysis;
using ModernLibs.FileHelpers.Generator.Models;

namespace ModernLibs.FileHelpers.Generator.Emission;

/// <summary>
/// Emits the file-scoped descriptor class and module-initializer registration class
/// for a single <see cref="RecordModel"/>.
/// Both classes are emitted into a single source file to avoid file-ordering non-determinism.
/// </summary>
internal static class DescriptorEmitter
{
    internal static void Emit(SourceProductionContext spc, RecordModel model)
    {
        var sb = new StringBuilder();

        // File header — auto-generated marker + nullable + CA2255 suppression.
        // CA2255: [ModuleInitializer] in source-generated consumer code is intentional.
        sb.AppendLine("// <auto-generated/>");
        sb.AppendLine("#nullable enable");
        sb.AppendLine("#pragma warning disable CA2255 // ModuleInitializer in source-generated consumer code");
        sb.AppendLine();

        // Optional file-scoped namespace declaration.
        if (!string.IsNullOrEmpty(model.Namespace))
        {
            sb.AppendLine($"namespace {model.Namespace};");
            sb.AppendLine();
        }

        // Fully-qualified type reference for the annotated record.
        // Roslyn INamedTypeSymbol.Name + ContainingNamespace are compiler-validated identifiers —
        // no injection risk (T-03-08: accept).
        string fqType = string.IsNullOrEmpty(model.Namespace)
            ? $"global::{model.TypeName}"
            : $"global::{model.Namespace}.{model.TypeName}";

        // ---- file-scoped descriptor class ----
        sb.AppendLine($"file sealed class __{model.TypeName}Descriptor : global::ModernLibs.FileHelpers.IRecordDescriptor<{fqType}>");
        sb.AppendLine("{");
        sb.AppendLine($"    public static readonly __{model.TypeName}Descriptor Instance = new();");
        sb.AppendLine();

        // Static cached converter fields for custom and DateMultiFormat converters (D-15).
        EmitConverterFields(sb, model.Fields);

        // Real inlined Parse body — Phase 5 implementation.
        EmitParseBody(sb, model, fqType);
        sb.AppendLine();

        // Real Format body — Phase 6 implementation via EmitFormatBody.
        EmitFormatBody(sb, model, fqType);
        sb.AppendLine();

        // Fields property backed by a static array — avoids per-call allocation.
        sb.AppendLine("    public global::System.ReadOnlySpan<global::ModernLibs.FileHelpers.FieldDescriptor> Fields =>");
        sb.AppendLine("        _fields.AsSpan();");
        sb.AppendLine();

        // Phase 7 D-07: emit RecordOptions initializer from record-level filter attributes.
        EmitOptionsProperty(sb, model);
        sb.AppendLine();

        // Static _fields array — fields are already sorted by Order in the extractor (SGEN-11).
        // T-03-09: empty Fields array (Length == 0) emits valid `[]` syntax — no runtime exception.
        sb.AppendLine("    private static readonly global::ModernLibs.FileHelpers.FieldDescriptor[] _fields =");
        sb.AppendLine("    [");

        // Compute running offset for fixed-length records; sentinel -1 for delimited.
        bool isFixed = string.Equals(model.RecordKind, "FixedLength", System.StringComparison.Ordinal);
        int runningOffset = 0;
        for (int i = 0; i < model.Fields.Length; i++)
        {
            var field = model.Fields[i];
            string comma = i < model.Fields.Length - 1 ? "," : "";
            int offset = isFixed ? runningOffset : -1;
            int width = isFixed ? field.FixedLength : -1;
            // nameof() and typeof() are AOT-safe compile-time literals (T-03-10: accept).
            sb.AppendLine($"        new(nameof({fqType}.{field.Name}), typeof({field.FullTypeName}), {field.Order}, {offset}, {width}){comma}");
            if (isFixed && field.FixedLength > 0) runningOffset += field.FixedLength;
        }
        sb.AppendLine("    ];");
        sb.AppendLine("}");
        sb.AppendLine();

        // ---- file-scoped registration class ----
        // [ModuleInitializer] requires at least internal accessibility (C# spec 9.2.4).
        // file-scoped class with internal static method satisfies both the file-scope isolation
        // and the accessibility constraint.
        sb.AppendLine($"file static class __{model.TypeName}Registration");
        sb.AppendLine("{");
        sb.AppendLine("    [global::System.Runtime.CompilerServices.ModuleInitializer]");
        sb.AppendLine("    internal static void Register()");
        sb.AppendLine("    {");
        sb.AppendLine($"        global::ModernLibs.FileHelpers.FileHelperRegistry<{fqType}>");
        sb.AppendLine($"            .SetDescriptor(__{model.TypeName}Descriptor.Instance);");
        sb.AppendLine("    }");
        sb.AppendLine("}");

        string sourceText = sb.ToString();

        // File name is deterministic: __ prefix + TypeName + .g.cs.
        // No timestamps or GUIDs — identical runs produce identical output (SGEN-11).
        spc.AddSource(
            $"__{model.TypeName}Descriptor.g.cs",
            Microsoft.CodeAnalysis.Text.SourceText.From(sourceText, System.Text.Encoding.UTF8));
    }

    /// <summary>
    /// Emits the fully-inlined <c>Parse</c> method body.
    /// D-04: no calls to FixedLengthSlicer or any other shared pipeline methods in generated code —
    /// all field splitting is inlined directly.
    /// D-05: inline TryParse calls per field type.
    /// </summary>
    private static void EmitParseBody(StringBuilder sb, RecordModel model, string fqType)
    {
        sb.AppendLine($"    public {fqType} Parse(global::System.ReadOnlySpan<char> line)");
        sb.AppendLine("    {");

        var fields = model.Fields;
        int fieldCount = fields.Length;

        if (fieldCount == 0)
        {
            // Edge case: no fields — emit direct construction with no field access.
            sb.AppendLine($"        return new {fqType}();");
            sb.AppendLine("    }");
            return;
        }

        bool isDelimited = string.Equals(model.RecordKind, "Delimited", System.StringComparison.Ordinal);
        bool hasQuotedField = HasAnyQuotedField(fields, fieldCount);

        // WR-03: when any field is [FieldQuoted], the escape path may rent a char[] from
        // ArrayPool<char>.Shared. Each quoted field has its own nullable local tracking
        // its rental; the finally block returns every non-null rental after the constructor
        // call so downstream TryParse / new string() can safely read through the span.
        if (hasQuotedField)
        {
            for (int i = 0; i < fieldCount; i++)
            {
                if (fields[i].IsQuoted)
                    sb.AppendLine($"        char[]? __qRent{i} = null;");
            }
            sb.AppendLine("        try");
            sb.AppendLine("        {");
        }

        if (isDelimited)
        {
            EmitDelimitedFieldSplitting(sb, model, fields, fieldCount);
        }
        else
        {
            EmitFixedLengthFieldSplitting(sb, fields, fieldCount);
        }

        // Phase 7 D-06: strip outer quotes and unescape doubled internal quotes BEFORE trim.
        // (RFC 4180 semantics: the quote wrapper is part of the raw field span on read.)
        EmitFieldQuotedStripPass(sb, fields, fieldCount);

        // Phase 7 D-05: apply [FieldTrim] to each field span AFTER quote stripping,
        // so a field like `" Alice "` first becomes ` Alice ` then `Alice`.
        EmitFieldTrimPass(sb, fields, fieldCount);

        // Inline TryParse conversions.
        sb.AppendLine();
        for (int i = 0; i < fieldCount; i++)
        {
            var field = fields[i];
            string tryParseCode = GetInlineTryParse($"__f{i}", field, i);
            sb.AppendLine($"        {tryParseCode}");
        }

        // Constructor call.
        // Use positional constructor only for struct types where all fields are init-only
        // (positional record struct syntax: readonly record struct Foo(int X, decimal Y)).
        // For class types, object initializer syntax works with both regular and init-only setters.
        // Field-based structs (record struct with public fields) also use object initializer.
        sb.AppendLine();
        bool isStructType = model.TypeKind.IndexOf("struct", System.StringComparison.OrdinalIgnoreCase) >= 0;
        bool allInitOnly = fieldCount > 0 && AllFieldsInitOnly(fields, fieldCount);
        bool usePositionalCtor = isStructType && allInitOnly;

        if (hasQuotedField)
        {
            // CLR guarantees: return expression is evaluated, then finally runs, then control
            // leaves the method. Downstream TryParse / new string() on __f{i} have already
            // materialised their values out of the rental by the time the finally returns it.
            EmitConstructorCall(sb, fqType, fields, fieldCount, usePositionalCtor);
            sb.AppendLine("        }");
            sb.AppendLine("        finally");
            sb.AppendLine("        {");
            for (int i = 0; i < fieldCount; i++)
            {
                if (fields[i].IsQuoted)
                {
                    sb.AppendLine($"            if (__qRent{i} is not null)");
                    sb.AppendLine($"                global::System.Buffers.ArrayPool<char>.Shared.Return(__qRent{i});");
                }
            }
            sb.AppendLine("        }");
        }
        else
        {
            EmitConstructorCall(sb, fqType, fields, fieldCount, usePositionalCtor);
        }

        sb.AppendLine("    }");
    }

    /// <summary>
    /// Returns true if any field in the model is marked with <see cref="FieldModel.IsQuoted"/>.
    /// Used to decide whether the Parse body wraps its work in a try/finally that returns
    /// rented char[] buffers from the quoted-field unescape path (WR-03).
    /// </summary>
    private static bool HasAnyQuotedField(EquatableArray<FieldModel> fields, int fieldCount)
    {
        for (int i = 0; i < fieldCount; i++)
        {
            if (fields[i].IsQuoted) return true;
        }
        return false;
    }

    /// <summary>
    /// Emits sequential IndexOf + slice splitting for delimited records (D-04: fully inlined).
    /// WR-04: when any field is <see cref="FieldModel.IsQuoted"/>, emits a quote-aware scanner
    /// that tracks "inside quotes" state so embedded delimiters inside a quoted payload do not
    /// prematurely close the field (RFC 4180 / FileHelpers 3.x parity).
    /// </summary>
    private static void EmitDelimitedFieldSplitting(
        StringBuilder sb,
        RecordModel model,
        EquatableArray<FieldModel> fields,
        int fieldCount)
    {
        // Determine delimiter char / string for emitted code.
        string delim = model.Delimiter;
        bool isSingleChar = delim.Length == 1;
        string delimLiteral = isSingleChar
            ? $"'{EscapeChar(delim[0])}'"
            : $"\"{EscapeString(delim)}\", global::System.StringComparison.Ordinal";
        int delimLen = delim.Length;

        // WR-04: quote-aware path when any field is [FieldQuoted].
        bool anyQuoted = HasAnyQuotedField(fields, fieldCount);
        if (anyQuoted)
        {
            EmitQuoteAwareDelimitedSplitting(sb, fields, fieldCount, delim);
            return;
        }

        for (int i = 0; i < fieldCount; i++)
        {
            bool isLast = i == fieldCount - 1;

            if (isLast)
            {
                // Last field: consume remainder of the remaining span.
                string remSpan = i == 0 ? "line" : $"__rem{i}";
                sb.AppendLine($"        var __f{i} = {remSpan};");
            }
            else
            {
                string srcSpan = i == 0 ? "line" : $"__rem{i}";
                sb.AppendLine($"        int __sep{i} = {srcSpan}.IndexOf({delimLiteral});");
                sb.AppendLine($"        var __f{i} = __sep{i} >= 0 ? {srcSpan}.Slice(0, __sep{i}) : {srcSpan};");
                sb.AppendLine($"        var __rem{i + 1} = __sep{i} >= 0 ? {srcSpan}.Slice(__sep{i} + {delimLen}) : global::System.ReadOnlySpan<char>.Empty;");
            }
        }
    }

    /// <summary>
    /// WR-04: Emits a quote-aware scanner for delimited records with at least one
    /// <see cref="FieldModel.IsQuoted"/> field. Tracks "inside quotes" state char-by-char
    /// so embedded delimiters inside a quoted payload do not terminate the field early.
    /// The scanner treats doubled quote chars as escapes (RFC 4180) and does not alter
    /// the raw field span — <see cref="EmitFieldQuotedStripPass"/> still strips the outer
    /// quote wrapper and unescapes doubled internals afterwards.
    /// Delimiter is assumed to be a single char for the fast path; multi-char delimiters
    /// fall back to a per-char scan matching the literal sequence.
    /// </summary>
    private static void EmitQuoteAwareDelimitedSplitting(
        StringBuilder sb,
        EquatableArray<FieldModel> fields,
        int fieldCount,
        string delim)
    {
        bool isSingleChar = delim.Length == 1;
        string delimFirst = $"'{EscapeChar(delim[0])}'";

        // Determine the quote character. In practice FH 3.x uses a single quote char per record;
        // we use the first quoted field's QuoteChar as the canonical one and assume all quoted
        // fields agree. Mixed quote chars on one record remain a v1.1 nicety.
        char qc = '"';
        for (int i = 0; i < fieldCount; i++)
        {
            if (fields[i].IsQuoted) { qc = fields[i].QuoteChar; break; }
        }
        string qLit = $"'{EscapeChar(qc)}'";

        sb.AppendLine("        // WR-04: quote-aware delimited splitting — delimiters inside the");
        sb.AppendLine("        // quoted payload do not terminate the field. Doubled quote chars inside");
        sb.AppendLine("        // a quoted span are treated as escape pairs and kept raw here —");
        sb.AppendLine("        // EmitFieldQuotedStripPass strips the outer quotes and collapses pairs.");
        sb.AppendLine("        int __qsPos = 0;");
        sb.AppendLine("        int __qsLen = line.Length;");
        for (int i = 0; i < fieldCount; i++)
        {
            bool isLast = i == fieldCount - 1;
            sb.AppendLine($"        int __qsStart{i} = __qsPos;");
            if (isLast)
            {
                // Consume remainder. Quote state is still correct up to EOL.
                sb.AppendLine($"        var __f{i} = line.Slice(__qsStart{i});");
                sb.AppendLine("        __qsPos = __qsLen;");
            }
            else
            {
                // Inline the scanner with a state local scoped to THIS field's loop.
                // Use a distinct local name per field (e.g. __qsIn0, __qsIn1) to avoid
                // cross-field shadowing at the method scope.
                sb.AppendLine($"        bool __qsIn{i} = false;");
                sb.AppendLine("        while (__qsPos < __qsLen)");
                sb.AppendLine("        {");
                sb.AppendLine("            char __qsCh = line[__qsPos];");
                sb.AppendLine($"            if (__qsCh == {qLit})");
                sb.AppendLine("            {");
                sb.AppendLine("                // Doubled quote inside a quoted span: skip pair and stay inside.");
                sb.AppendLine($"                if (__qsIn{i} && __qsPos + 1 < __qsLen && line[__qsPos + 1] == {qLit})");
                sb.AppendLine("                {");
                sb.AppendLine("                    __qsPos += 2;");
                sb.AppendLine("                    continue;");
                sb.AppendLine("                }");
                sb.AppendLine($"                __qsIn{i} = !__qsIn{i};");
                sb.AppendLine("                __qsPos++;");
                sb.AppendLine("                continue;");
                sb.AppendLine("            }");
                if (isSingleChar)
                {
                    sb.AppendLine($"            if (!__qsIn{i} && __qsCh == {delimFirst}) break;");
                }
                else
                {
                    // Multi-char delimiter: check full literal match starting at __qsPos.
                    sb.AppendLine($"            if (!__qsIn{i} && __qsCh == {delimFirst} && __qsPos + {delim.Length} <= __qsLen");
                    for (int di = 1; di < delim.Length; di++)
                    {
                        string delimChLit = $"'{EscapeChar(delim[di])}'";
                        sb.AppendLine($"                && line[__qsPos + {di}] == {delimChLit}");
                    }
                    sb.AppendLine("            ) break;");
                }
                sb.AppendLine("            __qsPos++;");
                sb.AppendLine("        }");
                sb.AppendLine($"        var __f{i} = line.Slice(__qsStart{i}, __qsPos - __qsStart{i});");
                // Advance past the delimiter that terminated the field (if any).
                sb.AppendLine($"        if (__qsPos < __qsLen) __qsPos += {delim.Length};");
            }
        }
    }

    /// <summary>
    /// Emits raw <c>line.Slice(offset, width)</c> arithmetic for fixed-length records (D-04: fully inlined).
    /// Using Math.Min for width clamping guards against short lines (D-03: lenient behavior).
    /// </summary>
    private static void EmitFixedLengthFieldSplitting(
        StringBuilder sb,
        EquatableArray<FieldModel> fields,
        int fieldCount)
    {
        int runningOffset = 0;
        for (int i = 0; i < fieldCount; i++)
        {
            var field = fields[i];
            int offset = runningOffset;
            int width = field.FixedLength > 0 ? field.FixedLength : 0;

            sb.AppendLine($"        var __f{i} = line.Length > {offset} ? line.Slice({offset}, global::System.Math.Min({width}, line.Length - {offset})) : global::System.ReadOnlySpan<char>.Empty;");

            if (field.FixedLength > 0) runningOffset += field.FixedLength;
        }
    }

    /// <summary>
    /// Returns true if every field in the model has <c>IsInitOnly = true</c>,
    /// indicating positional record constructor syntax is valid.
    /// Field-based structs (e.g., <c>record struct</c> with public fields) return false.
    /// </summary>
    private static bool AllFieldsInitOnly(EquatableArray<FieldModel> fields, int fieldCount)
    {
        for (int i = 0; i < fieldCount; i++)
        {
            if (!fields[i].IsInitOnly) return false;
        }
        return true;
    }

    /// <summary>
    /// Emits the constructor call.
    /// Positional syntax (<c>new T(v0, v1)</c>) is used only when all fields are init-only
    /// (positional record structs/classes). All other types use object initializer syntax.
    /// </summary>
    private static void EmitConstructorCall(
        StringBuilder sb,
        string fqType,
        EquatableArray<FieldModel> fields,
        int fieldCount,
        bool usePositionalConstructor)
    {
        if (usePositionalConstructor)
        {
            // Positional constructor: new T(__v0, __v1, __v2)
            var args = new StringBuilder();
            for (int i = 0; i < fieldCount; i++)
            {
                if (i > 0) args.Append(", ");
                args.Append($"__v{i}");
            }
            sb.AppendLine($"        return new {fqType}({args});");
        }
        else
        {
            // Object initializer: new T { Prop0 = __v0, Prop1 = __v1, ... }
            sb.AppendLine($"        return new {fqType}");
            sb.AppendLine("        {");
            for (int i = 0; i < fieldCount; i++)
            {
                string comma = i < fieldCount - 1 ? "," : "";
                sb.AppendLine($"            {fields[i].Name} = __v{i}{comma}");
            }
            sb.AppendLine("        };");
        }
    }

    /// <summary>
    /// Returns the inline TryParse (or string construction) statement for a single field.
    /// D-14: decision tree — explicit ConverterKind, custom type, then Phase 5 inline switch,
    /// then DateTime/DateOnly/TimeOnly fallback via built-in converters.
    /// Generator targets netstandard2.0: no range/index syntax; use Substring instead of slice.
    /// </summary>
    private static string GetInlineTryParse(string fieldVar, FieldModel field, int fieldIdx)
    {
        string typeName = field.TypeName;
        string fullTypeName = field.FullTypeName;

        // D-14: Step 1 — explicit ConverterKind annotation
        if (field.ConverterKind != GeneratorConverterKind.None)
        {
            return EmitBuiltInConverterTryParse(fieldVar, field, fieldIdx);
        }

        // D-14: Step 2 — custom type annotation (ConverterBase subclass wrapped in ConverterBaseAdapter<T>)
        if (field.ConverterTypeName is not null)
        {
            return EmitCustomConverterTryParse(fieldVar, field, fieldIdx);
        }

        // D-14: Steps 3–5: no annotation → fall through to Phase 5 inline switch
        // Normalize: strip "global::" prefix and "?" nullable suffix for comparison.
        const string globalPrefix = "global::";
        string normalized = typeName.TrimEnd('?');
        if (normalized.StartsWith(globalPrefix, System.StringComparison.Ordinal))
            normalized = normalized.Substring(globalPrefix.Length);

        // Also normalize fullTypeName for fallback matching.
        string normalizedFull = fullTypeName.TrimEnd('?');
        if (normalizedFull.StartsWith(globalPrefix, System.StringComparison.Ordinal))
            normalizedFull = normalizedFull.Substring(globalPrefix.Length);

        string? result = GetTryParseForNormalizedType(fieldVar, normalized, fieldIdx);
        if (result != null)
            return result;

        result = GetTryParseForNormalizedType(fieldVar, normalizedFull, fieldIdx);
        if (result != null)
            return result;

        // D-14: Step 4 — DateTime/DateOnly/TimeOnly without annotation → built-in converter
        if (string.Equals(normalized, "DateTime", System.StringComparison.Ordinal) ||
            string.Equals(normalizedFull, "System.DateTime", System.StringComparison.Ordinal))
            return $"if (!global::ModernLibs.FileHelpers.Converters.DateTimeConverter.Instance.TryParse({fieldVar}, out var __v{fieldIdx})) __v{fieldIdx} = default;";

        if (string.Equals(normalized, "DateOnly", System.StringComparison.Ordinal) ||
            string.Equals(normalizedFull, "System.DateOnly", System.StringComparison.Ordinal))
            return $"if (!global::ModernLibs.FileHelpers.Converters.DateOnlyConverter.Instance.TryParse({fieldVar}, out var __v{fieldIdx})) __v{fieldIdx} = default;";

        if (string.Equals(normalized, "TimeOnly", System.StringComparison.Ordinal) ||
            string.Equals(normalizedFull, "System.TimeOnly", System.StringComparison.Ordinal))
            return $"if (!global::ModernLibs.FileHelpers.Converters.TimeOnlyConverter.Instance.TryParse({fieldVar}, out var __v{fieldIdx})) __v{fieldIdx} = default;";

        // D-14: Step 5 — Enum without annotation: deferred to Phase 7 (requires IsEnum in FieldModel)
        // Emit default(T) with a comment — implicit enum dispatch requires TypeKind.Enum in FieldModel.
        return $"var __v{fieldIdx} = default({fullTypeName}); // TODO Phase 7: implicit enum dispatch (add IsEnum to FieldModel)";
    }

    /// <summary>
    /// Emits a built-in converter TryParse call for the given ConverterKind.
    /// T-06-04-01: exhaustive switch with InvalidOperationException for unknown values.
    /// </summary>
    private static string EmitBuiltInConverterTryParse(string fieldVar, FieldModel field, int fieldIdx)
    {
        // DateMultiFormat needs constructor args — handled separately with static cached field
        if (field.ConverterKind == GeneratorConverterKind.DateMultiFormat)
            return EmitDateMultiFormatTryParse(fieldVar, field, fieldIdx);

        string converterClass = field.ConverterKind switch
        {
            GeneratorConverterKind.Date => "global::ModernLibs.FileHelpers.Converters.DateTimeConverter",
            GeneratorConverterKind.Byte => "global::ModernLibs.FileHelpers.Converters.ByteConverter",
            GeneratorConverterKind.SByte => "global::ModernLibs.FileHelpers.Converters.SByteConverter",
            GeneratorConverterKind.Int16 => "global::ModernLibs.FileHelpers.Converters.Int16Converter",
            GeneratorConverterKind.Int32 => "global::ModernLibs.FileHelpers.Converters.Int32Converter",
            GeneratorConverterKind.Int64 => "global::ModernLibs.FileHelpers.Converters.Int64Converter",
            GeneratorConverterKind.UInt16 => "global::ModernLibs.FileHelpers.Converters.UInt16Converter",
            GeneratorConverterKind.UInt32 => "global::ModernLibs.FileHelpers.Converters.UInt32Converter",
            GeneratorConverterKind.UInt64 => "global::ModernLibs.FileHelpers.Converters.UInt64Converter",
            GeneratorConverterKind.Decimal => "global::ModernLibs.FileHelpers.Converters.DecimalConverter",
            GeneratorConverterKind.Double => "global::ModernLibs.FileHelpers.Converters.DoubleConverter",
            GeneratorConverterKind.Single => "global::ModernLibs.FileHelpers.Converters.SingleConverter",
            GeneratorConverterKind.PercentDouble => "global::ModernLibs.FileHelpers.Converters.PercentDoubleConverter",
            GeneratorConverterKind.Boolean => "global::ModernLibs.FileHelpers.Converters.BoolConverter",
            GeneratorConverterKind.Char => "global::ModernLibs.FileHelpers.Converters.CharConverter",
            GeneratorConverterKind.Guid => "global::ModernLibs.FileHelpers.Converters.GuidConverter",
            _ => throw new System.InvalidOperationException($"Unhandled GeneratorConverterKind {field.ConverterKind}")
        };

        return $"if (!{converterClass}.Instance.TryParse({fieldVar}, out var __v{fieldIdx})) __v{fieldIdx} = default;";
    }

    /// <summary>
    /// Emits a DateMultiFormatConverter TryParse call using a static cached field.
    /// The cached field declaration is emitted by <see cref="EmitConverterFields"/>.
    /// </summary>
    private static string EmitDateMultiFormatTryParse(string fieldVar, FieldModel field, int fieldIdx)
    {
        // __conv_field{fieldIdx} is a static cached DateMultiFormatConverter instance
        // declared by EmitConverterFields in the generated descriptor class body.
        return $"if (!__conv_field{fieldIdx}.TryParse({fieldVar}, out var __v{fieldIdx})) __v{fieldIdx} = default;";
    }

    /// <summary>
    /// Emits a custom ConverterBase subclass TryParse call via ConverterBaseAdapter.
    /// The static cached adapter field is declared by <see cref="EmitConverterFields"/>.
    /// Phase 6: all custom converter types (ConverterTypeName != null) are assumed to be
    /// ConverterBase subclasses wrapped with ConverterBaseAdapter&lt;T&gt;.
    /// Direct ISpanConverter&lt;T&gt; implementors are Phase 7 work.
    /// </summary>
    private static string EmitCustomConverterTryParse(string fieldVar, FieldModel field, int fieldIdx)
    {
        // __conv_field{fieldIdx} is a static cached ConverterBaseAdapter<T> instance
        // declared by EmitConverterFields in the generated descriptor class body.
        return $"if (!__conv_field{fieldIdx}.TryParse({fieldVar}, out var __v{fieldIdx})) __v{fieldIdx} = default; // Legacy ConverterBase adapter — allocates strings per field. Implement ISpanConverter<T> for zero-alloc.";
    }

    /// <summary>
    /// Emits static cached converter field declarations inside the generated descriptor class.
    /// Called for fields that have <see cref="FieldModel.ConverterTypeName"/> != null
    /// or <see cref="FieldModel.ConverterKind"/> == <see cref="GeneratorConverterKind.DateMultiFormat"/>.
    /// D-15: static cached fields, private static readonly, initialized once.
    /// </summary>
    private static void EmitConverterFields(StringBuilder sb, EquatableArray<FieldModel> fields)
    {
        bool anyEmitted = false;
        for (int i = 0; i < fields.Length; i++)
        {
            var field = fields[i];

            if (field.ConverterKind == GeneratorConverterKind.DateMultiFormat)
            {
                // Build the string[] literal for the formats argument
                var fmtArgs = field.ConverterArgs;
                var fmtLiteral = new System.Text.StringBuilder("new string[] { ");
                for (int ai = 0; ai < fmtArgs.Length; ai++)
                {
                    if (ai > 0) fmtLiteral.Append(", ");
                    fmtLiteral.Append('"');
                    fmtLiteral.Append(EscapeString(fmtArgs[ai]));
                    fmtLiteral.Append('"');
                }
                fmtLiteral.Append(" }");

                sb.AppendLine($"    private static readonly global::ModernLibs.FileHelpers.Converters.DateMultiFormatConverter __conv_field{i}");
                sb.AppendLine($"        = new({fmtLiteral});");
                anyEmitted = true;
            }
            else if (field.ConverterTypeName is not null)
            {
                // ConverterBase subclass wrapped with ConverterBaseAdapter<T>
                // Phase 6: assumes all custom types are ConverterBase subclasses (Phase 7 detects ISpanConverter<T>)
                sb.AppendLine($"    // Legacy ConverterBase adapter — allocates strings per field. Implement ISpanConverter<T> for zero-alloc.");
                sb.AppendLine($"    private static readonly global::ModernLibs.FileHelpers.Converters.ConverterBaseAdapter<{field.FullTypeName}> __conv_field{i}");
                sb.AppendLine($"        = new(new {field.ConverterTypeName}());");
                anyEmitted = true;
            }
        }

        if (anyEmitted) sb.AppendLine();
    }

    private static string? GetTryParseForNormalizedType(string fieldVar, string typeName, int fieldIdx)
    {
        if (string.Equals(typeName, "string", System.StringComparison.Ordinal) ||
