    /// <summary>
    /// Emits static cached converter field declarations inside the generated descriptor class.
    /// Called for fields that have <see cref="FieldModel.ConverterTypeName"/> != null
    /// or <see cref="FieldModel.ConverterKind"/> == <see cref="GeneratorConverterKind.DateMultiFormat"/>.
    /// D-15: static cached fields, private static readonly, initialized once.
    /// </summary>
    private static void EmitConverterFields(StringBuilder sb, EquatableArray<FieldModel> fields)
    {
        bool anyEmitted = false;
        for (int i = 0; i < fields.Length; i++)
        {
            var field = fields[i];

            if (field.ConverterKind == GeneratorConverterKind.DateMultiFormat)
            {
                // Build the string[] literal for the formats argument
                var fmtArgs = field.ConverterArgs;
                var fmtLiteral = new System.Text.StringBuilder("new string[] { ");
                for (int ai = 0; ai < fmtArgs.Length; ai++)
                {
                    if (ai > 0) fmtLiteral.Append(", ");
                    fmtLiteral.Append('"');
                    fmtLiteral.Append(EscapeString(fmtArgs[ai]));
                    fmtLiteral.Append('"');
                }
                fmtLiteral.Append(" }");

                // Phase 51 GAP-04: pass culture if specified
                string? cultureName = field.CultureName;
                string cultureArg = !string.IsNullOrEmpty(cultureName)
                    ? $", __culture_{cultureName!.Replace('-', '_')}"
                    : string.Empty;

                sb.AppendLine($"    private static readonly global::ModernLibs.FileHelpers.Converters.DateMultiFormatConverter __conv_field{i}");
                sb.AppendLine($"        = new({fmtLiteral}{cultureArg});");
                anyEmitted = true;
            }
            // Phase 51 GAP-04: Date converter with format and/or culture
            else if (field.ConverterKind == GeneratorConverterKind.Date
                     && (field.ConverterArgs.Length > 0 || !string.IsNullOrEmpty(field.CultureName)))
            {
                string? cultureName = field.CultureName;
                string cultureArg = !string.IsNullOrEmpty(cultureName)
                    ? $"__culture_{cultureName!.Replace('-', '_')}"
                    : "null";

                if (field.ConverterArgs.Length > 0)
                {
                    string formatArg = $"\"{EscapeString(field.ConverterArgs[0])}\"";
                    sb.AppendLine($"    private static readonly global::ModernLibs.FileHelpers.Converters.DateTimeConverter __conv_field{i}");
                    sb.AppendLine($"        = new({formatArg}, {cultureArg});");
                }
                else
                {
                    sb.AppendLine($"    private static readonly global::ModernLibs.FileHelpers.Converters.DateTimeConverter __conv_field{i}");
                    sb.AppendLine($"        = new(null, {cultureArg});");
                }
                anyEmitted = true;
            }
            else if (field.ConverterTypeName is not null)
            {
                if (field.DirectSpanConverter)
                {
                    sb.AppendLine($"    private static readonly {field.ConverterTypeName} __conv_field{i} = new();");
                }
                else
                {
                    // ConverterBase subclass wrapped with ConverterBaseAdapter<T>
                    sb.AppendLine($"    // Legacy ConverterBase adapter — allocates strings per field. Implement ISpanConverter<T> for zero-alloc.");
                    sb.AppendLine($"    private static readonly global::ModernLibs.FileHelpers.Converters.ConverterBaseAdapter<{field.FullTypeName}> __conv_field{i}");
                    sb.AppendLine($"        = new(new {field.ConverterTypeName}());");
                }

                anyEmitted = true;
            }
        }

        if (anyEmitted) sb.AppendLine();
    }

    /// <summary>
    /// Phase 51 GAP-04: Emit static cached CultureInfo fields for each unique culture name.
    /// Uses GetCultureInfo() which is AOT-safe and caches instances internally.
    /// </summary>
    private static void EmitCultureFields(StringBuilder sb, EquatableArray<FieldModel> fields)
    {
        var cultureNames = new System.Collections.Generic.HashSet<string>(System.StringComparer.Ordinal);
        foreach (var field in fields)
        {
            string? cn = field.CultureName;
            if (!string.IsNullOrEmpty(cn))
                cultureNames.Add(cn!);
        }

        foreach (var cultureName in cultureNames)
        {
            string safeName = cultureName.Replace('-', '_');
            sb.AppendLine($"    private static readonly global::System.Globalization.CultureInfo __culture_{safeName}");
            sb.AppendLine($"        = global::System.Globalization.CultureInfo.GetCultureInfo(\"{cultureName}\");");
        }

        if (cultureNames.Count > 0) sb.AppendLine();
    }

    /// <summary>
    /// Phase 51 GAP-04: Returns the converter instance expression for a built-in converter.
    /// When CultureName is specified, emits `new ConverterClass(__culture_X)` for numeric converters
    /// or `new ConverterClass(null, __culture_X)` for date converters (format, culture signature).
    /// </summary>
    private static string GetConverterInstanceExpression(FieldModel field, string converterClass)
    {
        string? cultureName = field.CultureName;
        if (!string.IsNullOrEmpty(cultureName))
        {
            string safeName = cultureName!.Replace('-', '_');
            // Date converters have (string? format, CultureInfo? culture) signature
            // Numeric converters have (IFormatProvider? culture) signature
            bool isDateConverter = converterClass.Contains("DateTimeConverter", StringComparison.Ordinal)
                || converterClass.Contains("DateOnlyConverter", StringComparison.Ordinal)
                || converterClass.Contains("TimeOnlyConverter", StringComparison.Ordinal);

            if (isDateConverter)
            {
                return $"new {converterClass}(null, __culture_{safeName})";
            }
            return $"new {converterClass}(__culture_{safeName})";
        }
        return $"{converterClass}.Instance";
    }

    private static string? GetTryParseForNormalizedType(string fieldVar, string typeName, int fieldIdx)
    {
        if (string.Equals(typeName, "string", System.StringComparison.Ordinal) ||
            string.Equals(typeName, "System.String", System.StringComparison.Ordinal))
            return $"string __v{fieldIdx} = new string({fieldVar});";

        if (string.Equals(typeName, "bool", System.StringComparison.Ordinal) ||
            string.Equals(typeName, "System.Boolean", System.StringComparison.Ordinal))
            return $"_ = bool.TryParse({fieldVar}, out bool __v{fieldIdx});";

        if (string.Equals(typeName, "int", System.StringComparison.Ordinal) ||
            string.Equals(typeName, "System.Int32", System.StringComparison.Ordinal))
            return $"_ = int.TryParse({fieldVar}, out int __v{fieldIdx});";

        if (string.Equals(typeName, "long", System.StringComparison.Ordinal) ||
            string.Equals(typeName, "System.Int64", System.StringComparison.Ordinal))
            return $"_ = long.TryParse({fieldVar}, out long __v{fieldIdx});";

        if (string.Equals(typeName, "short", System.StringComparison.Ordinal) ||
            string.Equals(typeName, "System.Int16", System.StringComparison.Ordinal))
            return $"_ = short.TryParse({fieldVar}, out short __v{fieldIdx});";

        if (string.Equals(typeName, "byte", System.StringComparison.Ordinal) ||
            string.Equals(typeName, "System.Byte", System.StringComparison.Ordinal))
            return $"_ = byte.TryParse({fieldVar}, out byte __v{fieldIdx});";

        if (string.Equals(typeName, "decimal", System.StringComparison.Ordinal) ||
            string.Equals(typeName, "System.Decimal", System.StringComparison.Ordinal))
            return $"_ = decimal.TryParse({fieldVar}, global::System.Globalization.NumberStyles.Any, global::System.Globalization.CultureInfo.InvariantCulture, out decimal __v{fieldIdx});";

        if (string.Equals(typeName, "double", System.StringComparison.Ordinal) ||
            string.Equals(typeName, "System.Double", System.StringComparison.Ordinal))
            return $"_ = double.TryParse({fieldVar}, global::System.Globalization.NumberStyles.Any, global::System.Globalization.CultureInfo.InvariantCulture, out double __v{fieldIdx});";

        if (string.Equals(typeName, "float", System.StringComparison.Ordinal) ||
            string.Equals(typeName, "System.Single", System.StringComparison.Ordinal))
            return $"_ = float.TryParse({fieldVar}, global::System.Globalization.NumberStyles.Any, global::System.Globalization.CultureInfo.InvariantCulture, out float __v{fieldIdx});";

        return null;
    }

    private static string EscapeChar(char c) => c switch
    {
        '\'' => "\\'",
        '\\' => "\\\\",
        '\n' => "\\n",
        '\r' => "\\r",
        '\t' => "\\t",
        _ => c.ToString(),
    };

    private static string EscapeString(string s)
    {
        var sb = new StringBuilder(s.Length);
        foreach (char c in s)
        {
            sb.Append(c switch
            {
                '"' => "\\\"",
                '\\' => "\\\\",
                '\n' => "\\n",
                '\r' => "\\r",
                '\t' => "\\t",
                _ => c.ToString(),
            });
        }
        return sb.ToString();
    }

    // ---- Format body emission (D-16, D-17, D-18, D-19) ----

    /// <summary>
    /// Emits the fully-inlined <c>Format</c> method body.
    /// D-16: no line terminator written here — the Phase 7 engine writes CRLF/LF after Format.
    /// D-19: symmetric in structure to EmitParseBody.
    /// </summary>
    private static void EmitFormatBody(StringBuilder sb, RecordModel model, string fqType)
    {
        sb.AppendLine($"    public void Format({fqType} record, global::System.Buffers.IBufferWriter<char> writer)");
        sb.AppendLine("    {");

        bool isDelimited = string.Equals(model.RecordKind, "Delimited", System.StringComparison.Ordinal);
        if (isDelimited)
            EmitDelimitedFormatFields(sb, model);
        else
            EmitFixedLengthFormatFields(sb, model);

        sb.AppendLine("    }");
    }

    /// <summary>
    /// D-17: Emits field writes for delimited records, separated by delimiter, no trailing delimiter.
    /// Single-char delimiter uses the fast path (Pattern C). Multi-char delimiter uses a for-loop.
    /// FDEL-02: Per-field delimiter support — delimiter between fields is determined by the NEXT field's
    /// delimiter override, or the record-level default if no override is specified.
    /// </summary>
    private static void EmitDelimitedFormatFields(StringBuilder sb, RecordModel model)
    {
        // Collect visible fields (same filter as Parse side).
        var allFields = model.Fields;
        int totalCount = 0;
        for (int i = 0; i < allFields.Length; i++)
        {
            if (!allFields[i].IsHidden && !allFields[i].IsValueDiscarded)
                totalCount++;
        }

        string recordDelim = model.Delimiter;

        int fieldIdx = 0;
        int visibleFieldIdx = 0;
        for (int i = 0; i < allFields.Length; i++)
        {
            var field = allFields[i];
            if (field.IsHidden || field.IsValueDiscarded) continue;

            bool isLastVisible = visibleFieldIdx == totalCount - 1;

            // Emit field write block.
            // Pass i (raw field-array index) as rawFieldIndex so __conv_field{i} references
            // match the declarations emitted by EmitConverterFields (which also uses raw index i).
            // fieldIdx (visible-field counter) is used only for unique local variable names.
            string fieldCode = GetFormatFieldCode(field, fieldIdx, rawFieldIndex: i);
            sb.AppendLine($"        {fieldCode}");

            // Emit delimiter between fields (not after the last field) — D-17
            // FDEL-02: The delimiter precedes the NEXT field, so we find the next visible
            // field and use its delimiter override, or fall back to record-level default.
            if (!isLastVisible)
            {
                // Find the next visible field to get its delimiter
                string nextDelimiter = recordDelim;
                for (int j = i + 1; j < allFields.Length; j++)
                {
                    if (!allFields[j].IsHidden && !allFields[j].IsValueDiscarded)
                    {
                        nextDelimiter = allFields[j].Delimiter ?? recordDelim;
                        break;
                    }
                }

                if (nextDelimiter.Length == 1)
                {
                    sb.AppendLine($"        {{ writer.GetSpan(1)[0] = '{EscapeChar(nextDelimiter[0])}'; writer.Advance(1); }}");
                }
                else
                {
                    // Multi-char delimiter — emit char-by-char via for-loop at generator time
                    int dlen = nextDelimiter.Length;
                    sb.AppendLine($"        {{");
                    sb.AppendLine($"            var __delim{fieldIdx} = writer.GetSpan({dlen});");
                    for (int di = 0; di < dlen; di++)
                    {
                        sb.AppendLine($"            __delim{fieldIdx}[{di}] = '{EscapeChar(nextDelimiter[di])}';");
                    }
                    sb.AppendLine($"            writer.Advance({dlen});");
                    sb.AppendLine($"        }}");
                }
            }

            fieldIdx++;
            visibleFieldIdx++;
        }
    }

    /// <summary>
    /// D-18: Emits field writes for fixed-length records. Each field always advances exactly W chars.
    /// Pre-fills with spaces, writes value, truncates if longer than W.
    /// FAVL-07, FAVL-10: Discarded fields still occupy space (write empty padding) to maintain alignment.
    /// </summary>
    private static void EmitFixedLengthFormatFields(StringBuilder sb, RecordModel model)
    {
        var allFields = model.Fields;
        int fieldIdx = 0;
        for (int i = 0; i < allFields.Length; i++)
        {
            var field = allFields[i];
            if (field.IsHidden) continue;

            int w = field.FixedLength > 0 ? field.FixedLength : 1;

            // FAVL-07, FAVL-10: Discarded fields occupy space but write empty padding
            if (field.IsValueDiscarded)
            {
                // Write empty space for discarded field (maintains fixed-length alignment)
                sb.AppendLine($"        {{ var __d{i} = writer.GetSpan({w}); __d{i}.Fill(' '); writer.Advance({w}); }} // [FieldValueDiscarded]");
                fieldIdx++;
                continue;
            }

            // Pass i (raw field-array index) as rawFieldIndex so __conv_field{i} references
            // match the declarations emitted by EmitConverterFields (which also uses raw index i).
            string fixedCode = GetFixedFormatFieldCode(field, fieldIdx, w, rawFieldIndex: i);
            sb.AppendLine($"        {fixedCode}");
            fieldIdx++;
        }
    }

    /// <summary>
    /// Returns the inline format statement for a single field in a delimited record.
    /// Patterns A (string), B (numeric TryFormat), D (converter TryFormat).
    /// </summary>
    /// <param name="field">Field model describing the field to format.</param>
    /// <param name="n">Visible-field counter — used for unique local variable names (__buf{n}, __d{n}, etc.).</param>
    /// <param name="rawFieldIndex">Raw field-array index — used for __conv_field{rawFieldIndex} references,
    /// which must match the index used in <see cref="EmitConverterFields"/>.</param>
    private static string GetFormatFieldCode(FieldModel field, int n, int rawFieldIndex)
    {
        // Phase 7 D-06: always-quote semantics — wrap output in quote chars with doubled internals.
        if (field.IsQuoted)
            return GetQuotedFormatFieldCode(field, n);

        string fieldRef = $"record.{field.Name}";
        string typeName = NormalizeTypeName(field.TypeName);
        string fullTypeName = NormalizeTypeName(field.FullTypeName);

        // Check for explicit converter annotation first (D-14 symmetry for Format)
        if (field.ConverterKind != GeneratorConverterKind.None &&
            field.ConverterKind != GeneratorConverterKind.DateMultiFormat)
        {
            string converterClass = GetBuiltInConverterClass(field.ConverterKind, field.FullTypeName);
            int bufSize = GetConverterBufferSize(field.ConverterKind);
            // Phase 51 GAP-04: use culture-aware converter instance when CultureName is specified
            string converterInstance = GetConverterInstanceExpression(field, converterClass);
            return $"{{ global::System.Span<char> __buf{n} = stackalloc char[{bufSize}]; {converterInstance}.TryFormat({fieldRef}, __buf{n}, out int __cw{n}); var __d{n} = writer.GetSpan(__cw{n}); __buf{n}[..__cw{n}].CopyTo(__d{n}); writer.Advance(__cw{n}); }}";
        }

        if (field.ConverterKind == GeneratorConverterKind.DateMultiFormat)
        {
            // DateMultiFormat: use static cached field (declared with raw index by EmitConverterFields).
            return $"{{ global::System.Span<char> __buf{n} = stackalloc char[20]; __conv_field{rawFieldIndex}.TryFormat({fieldRef}, __buf{n}, out int __cw{n}); var __d{n} = writer.GetSpan(__cw{n}); __buf{n}[..__cw{n}].CopyTo(__d{n}); writer.Advance(__cw{n}); }}";
        }

        if (field.ConverterTypeName is not null)
        {
            // Custom ConverterBase adapter (declared with raw index by EmitConverterFields).
            return $"{{ global::System.Span<char> __buf{n} = stackalloc char[256]; __conv_field{rawFieldIndex}.TryFormat({fieldRef}, __buf{n}, out int __cw{n}); var __d{n} = writer.GetSpan(__cw{n}); __buf{n}[..__cw{n}].CopyTo(__d{n}); writer.Advance(__cw{n}); }}";
        }

        // Pattern A — string (with optional alignment for delimited records with FieldFixedLength)
        if (IsStringType(typeName, fullTypeName))
        {
            // Phase 12: If AlignMode is set and FixedLength is specified, apply alignment
            if (field.AlignMode.HasValue && field.FixedLength > 0)
            {
                string padChar = field.AlignChar.HasValue ? $"'{EscapeChar(field.AlignChar.Value)}'" : "' '";
                int w = field.FixedLength;
                return EmitDelimitedAlignedStringCode(n, w, fieldRef, padChar, field.AlignMode.Value);
            }
            return $"{{ var __s{n} = {fieldRef} ?? \"\"; var __d{n} = writer.GetSpan(__s{n}.Length); __s{n}.AsSpan().CopyTo(__d{n}); writer.Advance(__s{n}.Length); }}";
        }

        // Pattern special — char
        if (IsCharType(typeName, fullTypeName))
            return $"{{ writer.GetSpan(1)[0] = {fieldRef}; writer.Advance(1); }}";

        // Pattern B — integer types (no culture)
        if (IsIntegerType(typeName, fullTypeName, out int intBufSize))
            return $"{{ global::System.Span<char> __buf{n} = stackalloc char[{intBufSize}]; {fieldRef}.TryFormat(__buf{n}, out int __cw{n}); var __d{n} = writer.GetSpan(__cw{n}); __buf{n}[..__cw{n}].CopyTo(__d{n}); writer.Advance(__cw{n}); }}";

        // Pattern D — floating-point (via built-in converters for InvariantCulture)
        if (IsDecimalType(typeName, fullTypeName))
        {
            string converterInstance = GetConverterInstanceExpression(field, "global::ModernLibs.FileHelpers.Converters.DecimalConverter");
            return $"{{ global::System.Span<char> __buf{n} = stackalloc char[32]; {converterInstance}.TryFormat({fieldRef}, __buf{n}, out int __cw{n}); var __d{n} = writer.GetSpan(__cw{n}); __buf{n}[..__cw{n}].CopyTo(__d{n}); writer.Advance(__cw{n}); }}";
        }

        if (IsDoubleType(typeName, fullTypeName))
        {
            string converterInstance = GetConverterInstanceExpression(field, "global::ModernLibs.FileHelpers.Converters.DoubleConverter");
            return $"{{ global::System.Span<char> __buf{n} = stackalloc char[24]; {converterInstance}.TryFormat({fieldRef}, __buf{n}, out int __cw{n}); var __d{n} = writer.GetSpan(__cw{n}); __buf{n}[..__cw{n}].CopyTo(__d{n}); writer.Advance(__cw{n}); }}";
        }

        if (IsSingleType(typeName, fullTypeName))
        {
            string converterInstance = GetConverterInstanceExpression(field, "global::ModernLibs.FileHelpers.Converters.SingleConverter");
            return $"{{ global::System.Span<char> __buf{n} = stackalloc char[16]; {converterInstance}.TryFormat({fieldRef}, __buf{n}, out int __cw{n}); var __d{n} = writer.GetSpan(__cw{n}); __buf{n}[..__cw{n}].CopyTo(__d{n}); writer.Advance(__cw{n}); }}";
        }

        // Pattern D — bool
        if (IsBoolType(typeName, fullTypeName))
            return $"{{ global::System.Span<char> __buf{n} = stackalloc char[6]; global::ModernLibs.FileHelpers.Converters.BoolConverter.Instance.TryFormat({fieldRef}, __buf{n}, out int __cw{n}); var __d{n} = writer.GetSpan(__cw{n}); __buf{n}[..__cw{n}].CopyTo(__d{n}); writer.Advance(__cw{n}); }}";

        // Pattern D — Guid
        if (IsGuidType(typeName, fullTypeName))
            return $"{{ global::System.Span<char> __buf{n} = stackalloc char[36]; global::ModernLibs.FileHelpers.Converters.GuidConverter.Instance.TryFormat({fieldRef}, __buf{n}, out int __cw{n}); var __d{n} = writer.GetSpan(__cw{n}); __buf{n}[..__cw{n}].CopyTo(__d{n}); writer.Advance(__cw{n}); }}";

        // Pattern D — DateTime, DateOnly, TimeOnly
        if (IsDateTimeType(typeName, fullTypeName))
            return $"{{ global::System.Span<char> __buf{n} = stackalloc char[20]; global::ModernLibs.FileHelpers.Converters.DateTimeConverter.Instance.TryFormat({fieldRef}, __buf{n}, out int __cw{n}); var __d{n} = writer.GetSpan(__cw{n}); __buf{n}[..__cw{n}].CopyTo(__d{n}); writer.Advance(__cw{n}); }}";

        if (IsDateOnlyType(typeName, fullTypeName))
            return $"{{ global::System.Span<char> __buf{n} = stackalloc char[12]; global::ModernLibs.FileHelpers.Converters.DateOnlyConverter.Instance.TryFormat({fieldRef}, __buf{n}, out int __cw{n}); var __d{n} = writer.GetSpan(__cw{n}); __buf{n}[..__cw{n}].CopyTo(__d{n}); writer.Advance(__cw{n}); }}";

        if (IsTimeOnlyType(typeName, fullTypeName))
            return $"{{ global::System.Span<char> __buf{n} = stackalloc char[10]; global::ModernLibs.FileHelpers.Converters.TimeOnlyConverter.Instance.TryFormat({fieldRef}, __buf{n}, out int __cw{n}); var __d{n} = writer.GetSpan(__cw{n}); __buf{n}[..__cw{n}].CopyTo(__d{n}); writer.Advance(__cw{n}); }}";

        // Fallback — ToString() for unrecognised types (object, enums without ISpanFormattable, etc.)
        // Safe for nullable reference types: ?? "" guards against null.
        return $"{{ var __s{n} = {fieldRef}?.ToString() ?? \"\"; var __d{n} = writer.GetSpan(__s{n}.Length); __s{n}.AsSpan().CopyTo(__d{n}); writer.Advance(__s{n}.Length); }}";
    }

    /// <summary>
    /// Returns the inline format statement for a single field in a fixed-length record (Pattern E).
    /// Always advances exactly W chars; pre-fills with spaces; truncates content > W.
    /// For string fields: copies up to W chars, leaves remaining as spaces.
    /// For value types: TryFormat into W-char stackalloc then copy.
    /// Phase 12: Supports [FieldAlign] for Left, Right, and Center alignment with custom pad chars.
    /// </summary>
    /// <param name="field">Field model describing the field to format.</param>
    /// <param name="n">Visible-field counter — used for unique local variable names (__buf{n}, __d{n}, etc.).</param>
    /// <param name="w">Fixed-length field width in chars.</param>
    /// <param name="rawFieldIndex">Raw field-array index — used for __conv_field{rawFieldIndex} references,
    /// which must match the index used in <see cref="EmitConverterFields"/>.</param>
    private static string GetFixedFormatFieldCode(FieldModel field, int n, int w, int rawFieldIndex)
    {
        string fieldRef = $"record.{field.Name}";
        string typeName = NormalizeTypeName(field.TypeName);
        string fullTypeName = NormalizeTypeName(field.FullTypeName);
        int formatBufferWidth = field.OverflowMode == 1 ? GetFixedOverflowBufferSize(field, w, typeName, fullTypeName) : w;

        // Determine pad character: use AlignChar if specified, otherwise space
        string padChar = field.AlignChar.HasValue ? $"'{EscapeChar(field.AlignChar.Value)}'" : "' '";

        // Phase 12: If AlignMode is specified, emit alignment-aware code
        if (field.AlignMode.HasValue)
        {
            return EmitAlignedFieldCode(field, n, w, rawFieldIndex, typeName, fullTypeName, fieldRef, padChar);
        }

        // String fields: direct copy up to W chars (no alignment)
        if (IsStringType(typeName, fullTypeName))
            return $"{{ var __d{n} = writer.GetSpan({w}); __d{n}.Fill(' '); var __s{n} = {fieldRef} ?? \"\";{GetStringOverflowGuard(field, n, w)} int __cp{n} = global::System.Math.Min(__s{n}.Length, {w}); __s{n}.AsSpan(0, __cp{n}).CopyTo(__d{n}); writer.Advance({w}); }}";

        // Char field
        if (IsCharType(typeName, fullTypeName))
            return $"{{ var __d{n} = writer.GetSpan({w}); __d{n}.Fill(' '); __d{n}[0] = {fieldRef}; writer.Advance({w}); }}";

        // Explicit converter annotation
        if (field.ConverterKind != GeneratorConverterKind.None &&
            field.ConverterKind != GeneratorConverterKind.DateMultiFormat)
        {
            string converterClass = GetBuiltInConverterClass(field.ConverterKind, field.FullTypeName);
            // Phase 51 GAP-04: use culture-aware converter instance when CultureName is specified
            string converterInstance = GetConverterInstanceExpression(field, converterClass);
            return $"{{ var __d{n} = writer.GetSpan({w}); __d{n}.Fill(' '); global::System.Span<char> __buf{n} = stackalloc char[{formatBufferWidth}]; bool __ok{n} = {converterInstance}.TryFormat({fieldRef}, __buf{n}, out int __cw{n});{GetFormattedOverflowGuard(field, n, w)} int __cp{n} = global::System.Math.Min(__cw{n}, {w}); __buf{n}[..__cp{n}].CopyTo(__d{n}); writer.Advance({w}); }}";
        }

        if (field.ConverterKind == GeneratorConverterKind.DateMultiFormat || field.ConverterTypeName is not null)
        {
            // Custom: TryFormat via cached adapter field (declared with raw index by EmitConverterFields).
            return $"{{ var __d{n} = writer.GetSpan({w}); __d{n}.Fill(' '); global::System.Span<char> __buf{n} = stackalloc char[{formatBufferWidth}]; bool __ok{n} = __conv_field{rawFieldIndex}.TryFormat({fieldRef}, __buf{n}, out int __cw{n});{GetFormattedOverflowGuard(field, n, w)} int __cp{n} = global::System.Math.Min(__cw{n}, {w}); __buf{n}[..__cp{n}].CopyTo(__d{n}); writer.Advance({w}); }}";
        }

        // Pattern E for all other value types: stackalloc W, TryFormat, truncate
        // Floating-point: use built-in converters for InvariantCulture
        if (IsDecimalType(typeName, fullTypeName))
        {
            string converterInstance = GetConverterInstanceExpression(field, "global::ModernLibs.FileHelpers.Converters.DecimalConverter");
            return $"{{ var __d{n} = writer.GetSpan({w}); __d{n}.Fill(' '); global::System.Span<char> __buf{n} = stackalloc char[{formatBufferWidth}]; bool __ok{n} = {converterInstance}.TryFormat({fieldRef}, __buf{n}, out int __cw{n});{GetFormattedOverflowGuard(field, n, w)} int __cp{n} = global::System.Math.Min(__cw{n}, {w}); __buf{n}[..__cp{n}].CopyTo(__d{n}); writer.Advance({w}); }}";
        }

        if (IsDoubleType(typeName, fullTypeName))
        {
            string converterInstance = GetConverterInstanceExpression(field, "global::ModernLibs.FileHelpers.Converters.DoubleConverter");
