    /// <summary>
    /// Returns a conservative stackalloc buffer size for the given built-in converter kind.
    /// Sizes from 06-RESEARCH.md §4.
    /// </summary>
    private static int GetConverterBufferSize(GeneratorConverterKind kind) => kind switch
    {
