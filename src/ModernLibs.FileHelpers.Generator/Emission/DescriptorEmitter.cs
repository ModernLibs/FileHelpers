    private static string Bool(bool value) => value ? "true" : "false";

    private static string SimpleTypeName(string typeName)
    {
        int lastDot = typeName.LastIndexOf('.');
        return lastDot >= 0 ? typeName.Substring(lastDot + 1) : typeName.Replace("global::", string.Empty);
    }

    private static string Literal(string value) => "\"" + EscapeString(value) + "\"";

    private static string CharLiteral(char c) => "'" + EscapeChar(c) + "'";

    private static string EscapeChar(char c) => c switch
    {
        '\'' => "\\'",
        '\\' => "\\\\",
        '\n' => "\\n",
        '\r' => "\\r",
        '\t' => "\\t",
        '\0' => "\\0",
        _ when char.IsControl(c) || char.IsSurrogate(c) => "\\u" + ((int)c).ToString("X4", System.Globalization.CultureInfo.InvariantCulture),
        _ => c.ToString(),
    };

    private static string EscapeString(string s)
    {
        var sb = new StringBuilder(s.Length);
        foreach (char c in s)
        {
            sb.Append(c switch
            {
                '"' => "\\\"",
                '\\' => "\\\\",
                '\n' => "\\n",
                '\r' => "\\r",
                '\t' => "\\t",
                '\0' => "\\0",
                _ when char.IsControl(c) => "\\u" + ((int)c).ToString("X4", System.Globalization.CultureInfo.InvariantCulture),
                _ => c.ToString(),
            });
        }
        return sb.ToString();
    }
