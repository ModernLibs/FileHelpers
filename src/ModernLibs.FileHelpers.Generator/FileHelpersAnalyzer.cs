using System.Collections.Immutable;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Diagnostics;
using ModernLibs.FileHelpers.Generator.Diagnostics;
using ModernLibs.FileHelpers.Generator.Extraction;
using ModernLibs.FileHelpers.Generator.Models;

namespace ModernLibs.FileHelpers.Generator;

/// <summary>
/// Reports the record validation diagnostics (MLFH001–MLFH019, MLFH021 and later rules).
/// </summary>
/// <remarks>
/// Diagnostics with source locations are reported by this analyzer instead of the incremental
/// generator. An analyzer always runs against the current compilation, so its locations are real
/// in-source locations (squiggles, <c>#pragma warning disable</c>, <c>[SuppressMessage]</c>), and no
/// cached diagnostic can refer to a syntax tree of an older compilation. The generator applies the same
/// rules (<see cref="RecordValidator"/>) only to decide whether a descriptor is emitted, and reports
/// nothing except MLFH020 (internal failure, not bound to a syntax tree). The blocking errors are not
/// configurable; when they are hidden anyway (<c>[SuppressMessage]</c>, or analyzers disabled with
/// <c>RunAnalyzers=false</c>) the generator registers a descriptor that throws a <c>BadUsageException</c>
/// naming the errors.
/// </remarks>
[DiagnosticAnalyzer(LanguageNames.CSharp)]
public sealed class FileHelpersAnalyzer : DiagnosticAnalyzer
{
    private const string DelimitedRecordAttribute = "ModernLibs.FileHelpers.DelimitedRecordAttribute";
    private const string FixedLengthRecordAttribute = "ModernLibs.FileHelpers.FixedLengthRecordAttribute";

    /// <inheritdoc />
    public override ImmutableArray<DiagnosticDescriptor> SupportedDiagnostics { get; } =
        ImmutableArray.Create(
            // Every rule except MLFH020, which only the generator reports.
            DiagnosticDescriptors.MLFH001MissingRecordAttribute,
            DiagnosticDescriptors.MLFH002MissingFixedLength,
            DiagnosticDescriptors.MLFH003AmbiguousFieldOrder,
            DiagnosticDescriptors.MLFH004UnrecognisedConverterType,
            DiagnosticDescriptors.MLFH005InvalidRegexPattern,
            DiagnosticDescriptors.MLFH006MissingParameterlessCtor,
            DiagnosticDescriptors.MLFH007ExcessiveFieldWidth,
            DiagnosticDescriptors.MLFH008FieldOrderGaps,
            DiagnosticDescriptors.MLFH009NoPublicFields,
            DiagnosticDescriptors.MLFH010IncompatibleNullValue,
            DiagnosticDescriptors.MLFH011ConflictingRecordAttributes,
            DiagnosticDescriptors.MLFH012EmptyDelimiter,
            DiagnosticDescriptors.MLFH013UnsupportedFieldType,
            DiagnosticDescriptors.MLFH014NoConstructionStrategy,
            DiagnosticDescriptors.MLFH015UnassignableMember,
            DiagnosticDescriptors.MLFH016GenericRecord,
            DiagnosticDescriptors.MLFH017InaccessibleRecord,
            DiagnosticDescriptors.MLFH018OptionalFieldOrder,
            DiagnosticDescriptors.MLFH019ConverterKindMismatch,
            DiagnosticDescriptors.MLFH021InvalidConverterArguments,
            DiagnosticDescriptors.MLFH022ConverterConstructorMismatch,
            DiagnosticDescriptors.MLFH023InaccessibleMember,
            DiagnosticDescriptors.MLFH024MixedFieldOrder,
            DiagnosticDescriptors.MLFH025QuotedFixedLengthField,
            DiagnosticDescriptors.MLFH026LanguageVersionTooLow,
            DiagnosticDescriptors.MLFH027RefStructRecord,
            DiagnosticDescriptors.MLFH028UnmappedLegacyMember,
            DiagnosticDescriptors.MLFH029FirstFieldInNewLineIgnoredAsEmpty);

    /// <inheritdoc />
    public override void Initialize(AnalysisContext context)
    {
        context.EnableConcurrentExecution();
        // Records declared in generated code (for example in a file marked <auto-generated>) are validated
        // like any other. A record added by another source generator is validated here too, but the
        // FileHelpers generator never sees it (generators do not see each other's output), so it gets no
        // descriptor and no diagnostic; docs/diagnostics.md documents this limitation.
        context.ConfigureGeneratedCodeAnalysis(GeneratedCodeAnalysisFlags.Analyze | GeneratedCodeAnalysisFlags.ReportDiagnostics);
        context.RegisterCompilationStartAction(static start =>
        {
            // Nothing to check when ModernLibs.FileHelpers is not referenced.
            if (start.Compilation.GetTypeByMetadataName(DelimitedRecordAttribute) is null
                && start.Compilation.GetTypeByMetadataName(FixedLengthRecordAttribute) is null)
            {
                return;
            }

            int maxFieldWidth = RecordValidator.ReadMaxFieldWidth(start.Options.AnalyzerConfigOptionsProvider.GlobalOptions);
            start.RegisterSymbolAction(ctx => AnalyzeRecord(ctx, maxFieldWidth), SymbolKind.NamedType);
            start.RegisterSyntaxNodeAction(AnalyzeEngineUsage, SyntaxKind.GenericName);
        });
    }

    /// <summary>Validates a type annotated with [DelimitedRecord] or [FixedLengthRecord].</summary>
    private static void AnalyzeRecord(SymbolAnalysisContext ctx, int maxFieldWidth)
    {
        if (ctx.Symbol is not INamedTypeSymbol type) return;

        AttributeData? delimited = null;
        AttributeData? fixedLength = null;
        foreach (var attribute in type.GetAttributes())
        {
            switch (attribute.AttributeClass?.ToDisplayString())
            {
                case DelimitedRecordAttribute:
                    delimited ??= attribute;
                    break;
                case FixedLengthRecordAttribute:
                    fixedLength ??= attribute;
                    break;
            }
        }
        if (delimited is null && fixedLength is null) return;

        // The generated code needs C# 11; the generator skips every record below that.
        if (ctx.Compilation is CSharpCompilation { LanguageVersion: < LanguageVersion.CSharp11 } csharp)
        {
            Location location = (delimited ?? fixedLength)!.ApplicationSyntaxReference?.GetSyntax(ctx.CancellationToken).GetLocation()
                                ?? type.Locations.FirstOrDefault()
                                ?? Location.None;
            ctx.ReportDiagnostic(Diagnostic.Create(DiagnosticDescriptors.MLFH026LanguageVersionTooLow, location,
                type.ToDisplayString(), csharp.LanguageVersion.ToDisplayString()));
        }

        try
        {
            // Same arm as the generator: a type with both attributes is reported (MLFH011) by the delimited arm.
            RecordModel? model = RecordModelExtractor.Extract(
                type, delimited ?? fixedLength!, ctx.Compilation, isFixed: delimited is null, bindToTree: true, ctx.CancellationToken);
            if (model is null) return;

            RecordValidator.Validate(model, maxFieldWidth, (descriptor, location, args) =>
                ctx.ReportDiagnostic(Diagnostic.Create(descriptor, location?.ToLocation() ?? Location.None, args)));
        }
        catch (Exception ex) when (ex is not OperationCanceledException)
        {
            // The generator reports the failure as MLFH020; reporting it twice would only add noise.
        }
    }

    /// <summary>
    /// MLFH001: <c>ModernLibs.FileHelpers.FileHelperRegistry`1</c> or <c>FileHelperEngine`1</c> (full
    /// metadata name — types with the same simple name, such as the original
    /// <c>FileHelpers.FileHelperEngine&lt;T&gt;</c>, are ignored) used with a type argument that lacks a record
    /// attribute. Located at the type argument.
    /// </summary>
    private static void AnalyzeEngineUsage(SyntaxNodeAnalysisContext ctx)
    {
        if (ctx.Node is not GenericNameSyntax gns) return;
        if (gns.Identifier.Text is not ("FileHelperRegistry" or "FileHelperEngine")) return;
        if (gns.TypeArgumentList.Arguments.Count != 1) return;

        if (ctx.SemanticModel.GetSymbolInfo(gns, ctx.CancellationToken).Symbol is not INamedTypeSymbol generic) return;
        INamedTypeSymbol definition = generic.OriginalDefinition;
        if (definition.MetadataName is not ("FileHelperRegistry`1" or "FileHelperEngine`1")) return;
        if (!string.Equals(definition.ContainingNamespace?.ToDisplayString(), "ModernLibs.FileHelpers", StringComparison.Ordinal)) return;

        TypeSyntax argument = gns.TypeArgumentList.Arguments[0];
        if (ctx.SemanticModel.GetTypeInfo(argument, ctx.CancellationToken).Type is not INamedTypeSymbol typeSymbol) return;
        if (typeSymbol.TypeKind == TypeKind.Error) return;

        foreach (var attr in typeSymbol.GetAttributes())
        {
            if (attr.AttributeClass?.ToDisplayString() is DelimitedRecordAttribute or FixedLengthRecordAttribute)
                return;
        }

        ctx.ReportDiagnostic(Diagnostic.Create(DiagnosticDescriptors.MLFH001MissingRecordAttribute, argument.GetLocation(), typeSymbol.Name));
    }
}
