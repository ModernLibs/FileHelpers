// MA0051: DescriptorEmitter.Emit is a single-responsibility string-building method.
// The length comes from emitting distinct code sections (header, namespace, descriptor class,
// parse body, format stub, fields array, registration class) — all required by the emitter contract.
// Extracting sub-methods would require passing model, sb, fqType, and TypeName as parameters
// for marginal readability gain. Suppression is intentional.
#pragma warning disable MA0051

using System.Text;
using Microsoft.CodeAnalysis;
using ModernLibs.FileHelpers.Generator.Models;

namespace ModernLibs.FileHelpers.Generator.Emission;

/// <summary>
/// Emits the file-scoped descriptor class and module-initializer registration class
/// for a single <see cref="RecordModel"/>.
/// Both classes are emitted into a single source file to avoid file-ordering non-determinism.
/// </summary>
internal static class DescriptorEmitter
{
    internal static void Emit(SourceProductionContext spc, RecordModel model)
    {
        var sb = new StringBuilder();

        // File header — auto-generated marker + nullable + CA2255 suppression.
        // CA2255: [ModuleInitializer] in source-generated consumer code is intentional.
        sb.AppendLine("// <auto-generated/>");
        sb.AppendLine("#nullable enable");
        sb.AppendLine("#pragma warning disable CA2255 // ModuleInitializer in source-generated consumer code");
        sb.AppendLine();

        // Optional file-scoped namespace declaration.
        if (!string.IsNullOrEmpty(model.Namespace))
        {
            sb.AppendLine($"namespace {model.Namespace};");
            sb.AppendLine();
        }

        // Fully-qualified type reference for the annotated record.
        // Roslyn INamedTypeSymbol.Name + ContainingNamespace are compiler-validated identifiers —
        // no injection risk (T-03-08: accept).
        string fqType = string.IsNullOrEmpty(model.Namespace)
            ? $"global::{model.TypeName}"
            : $"global::{model.Namespace}.{model.TypeName}";

        // ---- file-scoped descriptor class ----
        // For ref struct types, emit a special descriptor that uses Parse(ref T, ...) instead of Parse(...)
        // since ref struct types cannot be return values or generic type arguments.
        // For class record types with mutable (non-init-only) fields, also implement
        // IRecyclableDescriptor<T> (ENGI-15 / Plan 04).
        //
        // Conditions to emit IRecyclableDescriptor<T>:
        //   1. TypeKind is a reference type (no "struct" in TypeKind string)
        //   2. All mapped fields are NOT init-only (init setters cannot be called from ParseInto)
        //
        // Struct types are excluded: value-type assignment copies by value — recycling is a no-op.
        // Record-class types with init-only properties are excluded: C# does not allow assigning
        // init-only properties outside of an object initializer or constructor.
        bool isReferenceType = model.TypeKind.IndexOf("struct", System.StringComparison.OrdinalIgnoreCase) < 0;
        bool hasAnyInitOnly = HasAnyInitOnlyField(model.Fields, model.Fields.Length);
        bool isClassType = isReferenceType && !hasAnyInitOnly;
        bool isRefStruct = model.IsRefStruct;

        string implements;
        if (isRefStruct)
        {
            // Ref struct types: emit a simple descriptor with Parse(ref T, ...) method
            // No interface implementation since ref struct can't be used as generic type arguments
            implements = "";
        }
        else if (isClassType)
        {
            implements = $" : global::ModernLibs.FileHelpers.IRecyclableDescriptor<{fqType}>";
        }
        else
        {
            implements = $" : global::ModernLibs.FileHelpers.IRecordDescriptor<{fqType}>";
        }
        sb.AppendLine($"file sealed class __{model.TypeName}Descriptor{implements}");
        sb.AppendLine("{");
        sb.AppendLine($"    public static readonly __{model.TypeName}Descriptor Instance = new();");
        sb.AppendLine();

        // Static cached converter fields for custom and DateMultiFormat converters (D-15).
        EmitConverterFields(sb, model.Fields);

        // Phase 51 GAP-04: Static cached CultureInfo fields for culture-aware parsing
        EmitCultureFields(sb, model.Fields);

        // Real inlined Parse body — Phase 5 implementation.
        // For ref struct types, emit Parse(ref T, ...) instead of Parse(...)
        if (isRefStruct)
        {
            EmitParseBodyRefStruct(sb, model, fqType);
        }
        else
        {
            EmitParseBody(sb, model, fqType);
        }
        sb.AppendLine();

        // ParseInto body — Phase 8 ENGI-15: emitted only for class record types.
        // Struct descriptors do not implement IRecyclableDescriptor<T>.
        if (isClassType)
        {
            EmitParseIntoBody(sb, model, fqType);
            sb.AppendLine();
        }

        // Format body — only emit for non-ref-struct types (ref struct can't be used with IBufferWriter)
        if (!isRefStruct)
        {
            EmitFormatBody(sb, model, fqType);
            sb.AppendLine();
        }

        // Fields property backed by a static array — avoids per-call allocation.
        sb.AppendLine("    public global::System.ReadOnlySpan<global::ModernLibs.FileHelpers.FieldDescriptor> Fields =>");
        sb.AppendLine("        _fields.AsSpan();");
        sb.AppendLine();

        // Phase 7 D-07: emit RecordOptions initializer from record-level filter attributes.
        EmitOptionsProperty(sb, model);
        sb.AppendLine();

        // LIMIT-02: Emit CreateDefaultInstance for INotifyRead<T>.BeforeRead support.
        // Structs: return default; Classes: return new T(); (parameterless ctor required)
        if (!isRefStruct)
        {
            sb.AppendLine($"    public {fqType} CreateDefaultInstance()");
            sb.AppendLine("    {");
            if (isReferenceType)
            {
                sb.AppendLine($"        return new {fqType}();");
            }
            else
            {
                sb.AppendLine($"        return default;");
            }
            sb.AppendLine("    }");
            sb.AppendLine();
        }

        // Static _fields array — fields are already sorted by Order in the extractor (SGEN-11).
        // T-03-09: empty Fields array (Length == 0) emits valid `[]` syntax — no runtime exception.
        sb.AppendLine("    private static readonly global::ModernLibs.FileHelpers.FieldDescriptor[] _fields =");
        sb.AppendLine("    [");

        // Compute running offset for fixed-length records; sentinel -1 for delimited.
        bool isFixed = string.Equals(model.RecordKind, "FixedLength", System.StringComparison.Ordinal);
        int runningOffset = 0;
        for (int i = 0; i < model.Fields.Length; i++)
        {
            var field = model.Fields[i];
            string comma = i < model.Fields.Length - 1 ? "," : "";
            int offset = isFixed ? runningOffset : -1;
            int width = isFixed ? field.FixedLength : -1;
            // FDEL-01: Emit per-field delimiter (null if not specified)
            string delimiterArg = field.Delimiter is not null
                ? $"\"{EscapeString(field.Delimiter)}\""
                : "null";
            // Phase 14 MLIN-01: Emit IsInNewLine for multi-line record support
            string isInNewLineArg = field.IsInNewLine ? "true" : "false";
            // Phase 50 GAP-02: Emit FieldCaption (null if not specified)
            string captionArg = field.Caption is not null
                ? $"\"{EscapeString(field.Caption)}\""
                : "null";
            // Phase 51 GAP-04: Emit CultureName (null if not specified)
            string cultureNameArg = field.CultureName is not null
                ? $"\"{EscapeString(field.CultureName)}\""
                : "null";
            // nameof() and typeof() are AOT-safe compile-time literals (T-03-10: accept).
            sb.AppendLine($"        new(nameof({fqType}.{field.Name}), typeof({field.FullTypeName}), {field.Order}, {offset}, {width}, {delimiterArg}, {isInNewLineArg}, {captionArg}, {cultureNameArg}){comma}");
            if (isFixed && field.FixedLength > 0) runningOffset += field.FixedLength;
        }
        sb.AppendLine("    ];");
        sb.AppendLine("}");
        sb.AppendLine();

        // ---- file-scoped registration class ----
        // [ModuleInitializer] requires at least internal accessibility (C# spec 9.2.4).
        // file-scoped class with internal static method satisfies both the file-scope isolation
        // and the accessibility constraint.
        // Ref struct types are NOT registered in FileHelperRegistry<T> because ref struct
        // cannot be used as generic type arguments. They are parsed directly via the descriptor.
        if (!isRefStruct)
        {
            sb.AppendLine($"file static class __{model.TypeName}Registration");
            sb.AppendLine("{");
            sb.AppendLine("    [global::System.Runtime.CompilerServices.ModuleInitializer]");
            sb.AppendLine("    internal static void Register()");
            sb.AppendLine("    {");
            sb.AppendLine($"        global::ModernLibs.FileHelpers.FileHelperRegistry<{fqType}>");
            sb.AppendLine($"            .SetDescriptor(__{model.TypeName}Descriptor.Instance);");
            sb.AppendLine("    }");
            sb.AppendLine("}");
        }

        string sourceText = sb.ToString();

        // File name is deterministic: __ prefix + TypeName + .g.cs.
        // No timestamps or GUIDs — identical runs produce identical output (SGEN-11).
        spc.AddSource(
            $"__{model.TypeName}Descriptor.g.cs",
            Microsoft.CodeAnalysis.Text.SourceText.From(sourceText, System.Text.Encoding.UTF8));
    }

    /// <summary>
    /// Emits the fully-inlined <c>Parse</c> method body.
    /// D-04: no calls to FixedLengthSlicer or any other shared pipeline methods in generated code —
    /// all field splitting is inlined directly.
    /// D-05: inline TryParse calls per field type.
    /// Phase 14 MLIN-02: Supports multi-line records with lineCount parameter.
    /// </summary>
    private static void EmitParseBody(StringBuilder sb, RecordModel model, string fqType)
    {
        sb.AppendLine($"    public {fqType} Parse(global::System.ReadOnlySpan<char> lines, int lineCount)");
        sb.AppendLine("    {");

        var fields = model.Fields;
        int fieldCount = fields.Length;

        if (fieldCount == 0)
        {
            // Edge case: no fields — emit direct construction with no field access.
            sb.AppendLine($"        return new {fqType}();");
            sb.AppendLine("    }");
            return;
        }

        // Phase 14 MLIN-02: Calculate expected line count based on IsInNewLine fields
        sb.AppendLine("        // Phase 14 MLIN-02: Multi-line record support");
        int expectedLineCount = 1;
        for (int i = 0; i < fieldCount; i++)
        {
            if (fields[i].IsInNewLine) expectedLineCount++;
        }
        sb.AppendLine($"        const int __expectedLines = {expectedLineCount}; // 1 + {expectedLineCount - 1} FieldInNewLine fields");
        sb.AppendLine("        if (lineCount != __expectedLines)");
        sb.AppendLine("            throw new global::System.FormatException($\"Expected {__expectedLines} lines for the record but received {lineCount}. Check that all multi-line fields are present.\");");
        sb.AppendLine("        var line = lines;");
        sb.AppendLine();

        bool isDelimited = string.Equals(model.RecordKind, "Delimited", System.StringComparison.Ordinal);
        bool hasQuotedField = HasAnyQuotedField(fields, fieldCount);
        bool hasMultiLine = expectedLineCount > 1;

        // Phase 14 MLIN-02: For multi-line records, split the lines first
        if (hasMultiLine)
        {
            EmitMultiLineSplitting(sb, expectedLineCount);
        }

        if (!isDelimited)
        {
            EmitFixedLengthModeValidation(sb, fields, fieldCount, model.FixedMode, hasMultiLine);
        }

        // WR-03: when any field is [FieldQuoted], the escape path may rent a char[] from
        // ArrayPool<char>.Shared. Each quoted field has its own nullable local tracking
        // its rental; the finally block returns every non-null rental after the constructor
        // call so downstream TryParse / new string() can safely read through the span.
        if (hasQuotedField)
        {
            for (int i = 0; i < fieldCount; i++)
            {
                if (fields[i].IsQuoted)
                    sb.AppendLine($"        char[]? __qRent{i} = null;");
            }
            sb.AppendLine("        try");
            sb.AppendLine("        {");
        }

        if (isDelimited)
        {
            EmitDelimitedFieldSplitting(sb, model, fields, fieldCount, hasMultiLine);
        }
        else
        {
            EmitFixedLengthFieldSplitting(sb, fields, fieldCount, hasMultiLine);
        }

        // Phase 7 D-06: strip outer quotes and unescape doubled internal quotes BEFORE trim.
        // (RFC 4180 semantics: the quote wrapper is part of the raw field span on read.)
        EmitFieldQuotedStripPass(sb, fields, fieldCount);

        // Phase 7 D-05: apply [FieldTrim] to each field span AFTER quote stripping,
        // so a field like `" Alice "` first becomes ` Alice ` then `Alice`.
        EmitFieldTrimPass(sb, fields, fieldCount);

        // Phase 13 FAVL-06: FieldNotEmpty validation after trim, before parse
        EmitFieldNotEmptyValidation(sb, fields, fieldCount);

        // Inline TryParse conversions.
        sb.AppendLine();
        for (int i = 0; i < fieldCount; i++)
        {
            var field = fields[i];
            string tryParseCode = GetInlineTryParse($"__f{i}", field, i);
            sb.AppendLine($"        {tryParseCode}");
        }

        // Constructor call.
        // Use positional constructor only for struct types where all fields are init-only
        // (positional record struct syntax: readonly record struct Foo(int X, decimal Y)).
        // For class types, object initializer syntax works with both regular and init-only setters.
        // Field-based structs (record struct with public fields) also use object initializer.
        sb.AppendLine();
        bool isStructType = model.TypeKind.IndexOf("struct", System.StringComparison.OrdinalIgnoreCase) >= 0;
        bool allInitOnly = fieldCount > 0 && AllFieldsInitOnly(fields, fieldCount);
        bool usePositionalCtor = isStructType && allInitOnly;

        if (hasQuotedField)
        {
            // CLR guarantees: return expression is evaluated, then finally runs, then control
            // leaves the method. Downstream TryParse / new string() on __f{i} have already
            // materialised their values out of the rental by the time the finally returns it.
            EmitConstructorCall(sb, fqType, fields, fieldCount, usePositionalCtor);
            sb.AppendLine("        }");
            sb.AppendLine("        finally");
            sb.AppendLine("        {");
            for (int i = 0; i < fieldCount; i++)
            {
                if (fields[i].IsQuoted)
                {
                    sb.AppendLine($"            if (__qRent{i} is not null)");
                    sb.AppendLine($"                global::System.Buffers.ArrayPool<char>.Shared.Return(__qRent{i});");
                }
            }
            sb.AppendLine("        }");
        }
        else
        {
            EmitConstructorCall(sb, fqType, fields, fieldCount, usePositionalCtor);
        }

        sb.AppendLine("    }");
    }

    /// <summary>
    /// Phase 44: Emits a Parse method for ref struct types that takes ref T record
    /// instead of returning T, since ref struct types cannot be return values.
    /// </summary>
    private static void EmitParseBodyRefStruct(StringBuilder sb, RecordModel model, string fqType)
    {
        sb.AppendLine($"    public void Parse(global::System.ReadOnlySpan<char> lines, int lineCount, ref {fqType} record)");
        sb.AppendLine("    {");

        var fields = model.Fields;
        int fieldCount = fields.Length;

        if (fieldCount == 0)
        {
            sb.AppendLine("    }");
            return;
        }

        sb.AppendLine("        // Phase 44: Ref struct parsing — assigns directly to record fields");
        sb.AppendLine("        const int __expectedLines = 1;");
        sb.AppendLine("        var line = lines;");
        sb.AppendLine();

        bool isDelimited = string.Equals(model.RecordKind, "Delimited", System.StringComparison.Ordinal);
        bool hasQuotedField = HasAnyQuotedField(fields, fieldCount);

        if (hasQuotedField)
        {
            for (int i = 0; i < fieldCount; i++)
            {
                if (fields[i].IsQuoted)
                    sb.AppendLine($"        char[]? __qRent{i} = null;");
            }
            sb.AppendLine("        try");
            sb.AppendLine("        {");
        }

        if (isDelimited)
        {
            EmitDelimitedFieldSplitting(sb, model, fields, fieldCount, hasMultiLine: false);
        }
        else
        {
            EmitFixedLengthFieldSplitting(sb, fields, fieldCount, hasMultiLine: false);
        }

        EmitFieldQuotedStripPass(sb, fields, fieldCount);
        EmitFieldTrimPass(sb, fields, fieldCount);
        EmitFieldNotEmptyValidation(sb, fields, fieldCount);

        sb.AppendLine();
        for (int i = 0; i < fieldCount; i++)
        {
            var field = fields[i];
            string tryParseCode = GetInlineTryParseRefStruct($"__f{i}", field, i);
            sb.AppendLine($"        {tryParseCode}");
        }

        if (hasQuotedField)
        {
            sb.AppendLine("        }");
            sb.AppendLine("        finally");
            sb.AppendLine("        {");
            for (int i = 0; i < fieldCount; i++)
            {
                if (fields[i].IsQuoted)
                {
                    sb.AppendLine($"            if (__qRent{i} is not null)");
                    sb.AppendLine($"                global::System.Buffers.ArrayPool<char>.Shared.Return(__qRent{i});");
                }
            }
            sb.AppendLine("        }");
        }

        sb.AppendLine("    }");
    }

    /// <summary>
    /// Phase 14 MLIN-02: Emits code to split concatenated lines into individual line spans.
    /// For a record with N lines, emits __line0, __line1, ... __line(N-1) locals.
    /// </summary>
    private static void EmitMultiLineSplitting(StringBuilder sb, int lineCount)
    {
        sb.AppendLine("        // Phase 14 MLIN-02: Split multi-line record into individual lines");
        sb.AppendLine("        var __remaining = lines;");
        for (int i = 0; i < lineCount; i++)
        {
            sb.AppendLine($"        int __nl{i} = __remaining.IndexOfAny('\\r', '\\n');");
            sb.AppendLine($"        var __line{i} = __nl{i} >= 0 ? __remaining.Slice(0, __nl{i}) : __remaining;");
            if (i < lineCount - 1)
            {
                sb.AppendLine($"        if (__nl{i} >= 0)");
                sb.AppendLine("        {");
                sb.AppendLine($"            __remaining = __remaining.Slice(__nl{i} + 1);");
                // Handle CRLF (\r\n) - if we found \r and next char is \n, skip it
                sb.AppendLine($"            if (__remaining.Length > 0 && __remaining[0] == '\\n')");
                sb.AppendLine($"                __remaining = __remaining.Slice(1);");
                sb.AppendLine("        }");
            }
        }
        sb.AppendLine();
    }

    /// <summary>
    /// Emits the <c>ParseInto(ReadOnlySpan&lt;char&gt; lines, int lineCount, T existing)</c> method body for class record types.
    /// ENGI-15 / Plan 04: identical field-extraction logic to <see cref="EmitParseBody"/> but
    /// assigns parsed values to <c>existing.FieldName</c> instead of constructing a new instance.
    /// Only emitted when <c>model.TypeKind</c> is a class (not struct).
    /// Phase 14 MLIN-02: Supports multi-line records with lineCount parameter.
    /// </summary>
    private static void EmitParseIntoBody(StringBuilder sb, RecordModel model, string fqType)
    {
        sb.AppendLine($"    public void ParseInto(global::System.ReadOnlySpan<char> lines, int lineCount, {fqType} existing)");
        sb.AppendLine("    {");

        var fields = model.Fields;
        int fieldCount = fields.Length;

        if (fieldCount == 0)
        {
            // No fields — nothing to assign.
            sb.AppendLine("    }");
            return;
        }

        // Phase 14 MLIN-02: Calculate expected line count based on IsInNewLine fields
        sb.AppendLine("        // Phase 14 MLIN-02: Multi-line record support");
        int expectedLineCount = 1;
        for (int i = 0; i < fieldCount; i++)
        {
            if (fields[i].IsInNewLine) expectedLineCount++;
        }
        sb.AppendLine($"        const int __expectedLines = {expectedLineCount}; // 1 + {expectedLineCount - 1} FieldInNewLine fields");
        sb.AppendLine("        if (lineCount != __expectedLines)");
        sb.AppendLine("            throw new global::System.FormatException($\"Expected {__expectedLines} lines for the record but received {lineCount}. Check that all multi-line fields are present.\");");
        sb.AppendLine("        var line = lines;");
        sb.AppendLine();

        bool isDelimited = string.Equals(model.RecordKind, "Delimited", System.StringComparison.Ordinal);
        bool hasQuotedField = HasAnyQuotedField(fields, fieldCount);
        bool hasMultiLine = expectedLineCount > 1;

        // Phase 14 MLIN-02: For multi-line records, split the lines first
        if (hasMultiLine)
        {
            EmitMultiLineSplitting(sb, expectedLineCount);
        }

        if (!isDelimited)
        {
            EmitFixedLengthModeValidation(sb, fields, fieldCount, model.FixedMode, hasMultiLine);
        }

        // Same quoted-field rental guards as Parse — rental is returned in finally after assignments.
        if (hasQuotedField)
        {
            for (int i = 0; i < fieldCount; i++)
            {
                if (fields[i].IsQuoted)
                    sb.AppendLine($"        char[]? __qRent{i} = null;");
            }
            sb.AppendLine("        try");
            sb.AppendLine("        {");
        }

        if (isDelimited)
        {
            EmitDelimitedFieldSplitting(sb, model, fields, fieldCount, hasMultiLine);
        }
        else
        {
            EmitFixedLengthFieldSplitting(sb, fields, fieldCount, hasMultiLine);
        }

        EmitFieldQuotedStripPass(sb, fields, fieldCount);
        EmitFieldTrimPass(sb, fields, fieldCount);

        // Phase 13 FAVL-06: FieldNotEmpty validation for ParseInto
        EmitFieldNotEmptyValidation(sb, fields, fieldCount);

        // Inline TryParse conversions — same as Parse.
        sb.AppendLine();
        for (int i = 0; i < fieldCount; i++)
        {
            var field = fields[i];
            string tryParseCode = GetInlineTryParse($"__f{i}", field, i);
            sb.AppendLine($"        {tryParseCode}");
        }

        // Assign parsed values to existing instance fields/properties instead of constructing new T.
        sb.AppendLine();
        if (hasQuotedField)
        {
            EmitParseIntoAssignments(sb, fields, fieldCount);
            sb.AppendLine("        }");
            sb.AppendLine("        finally");
            sb.AppendLine("        {");
            for (int i = 0; i < fieldCount; i++)
            {
                if (fields[i].IsQuoted)
                {
                    sb.AppendLine($"            if (__qRent{i} is not null)");
                    sb.AppendLine($"                global::System.Buffers.ArrayPool<char>.Shared.Return(__qRent{i});");
                }
            }
            sb.AppendLine("        }");
        }
        else
        {
            EmitParseIntoAssignments(sb, fields, fieldCount);
        }

        sb.AppendLine("    }");
    }

    /// <summary>
    /// Emits direct field/property assignments to <c>existing</c> for <see cref="EmitParseIntoBody"/>.
    /// Replaces the constructor call in <see cref="EmitParseBody"/> with <c>existing.FieldN = __vN;</c> statements.
    /// FAVL-07, FAVL-10: Fields marked with IsValueDiscarded are skipped in ParseInto.
    /// </summary>
    private static void EmitParseIntoAssignments(
        StringBuilder sb,
        EquatableArray<FieldModel> fields,
        int fieldCount)
    {
        for (int i = 0; i < fieldCount; i++)
        {
            if (fields[i].IsValueDiscarded) continue;  // FAVL-07: skip discarded
            sb.AppendLine($"        existing.{fields[i].Name} = __v{i};");
        }
    }

    /// <summary>
    /// Returns true if any field in the model is marked with <see cref="FieldModel.IsQuoted"/>.
    /// Used to decide whether the Parse body wraps its work in a try/finally that returns
    /// rented char[] buffers from the quoted-field unescape path (WR-03).
    /// </summary>
    private static bool HasAnyQuotedField(EquatableArray<FieldModel> fields, int fieldCount)
    {
        for (int i = 0; i < fieldCount; i++)
        {
            if (fields[i].IsQuoted) return true;
        }
        return false;
    }

    /// <summary>
    /// Emits sequential IndexOf + slice splitting for delimited records (D-04: fully inlined).
    /// WR-04: when any field is <see cref="FieldModel.IsQuoted"/>, emits a quote-aware scanner
    /// that tracks "inside quotes" state so embedded delimiters inside a quoted payload do not
    /// prematurely close the field (RFC 4180 / FileHelpers 3.x parity).
    /// FDEL-02: per-field delimiter support — each field can have its own delimiter override.
    /// Phase 14 MLIN-02: For multi-line records, fields with IsInNewLine use their corresponding line.
    /// </summary>
    private static void EmitDelimitedFieldSplitting(
        StringBuilder sb,
        RecordModel model,
        EquatableArray<FieldModel> fields,
        int fieldCount,
        bool hasMultiLine = false)
    {
        // WR-04: quote-aware path when any field is [FieldQuoted].
        bool anyQuoted = HasAnyQuotedField(fields, fieldCount);
        if (anyQuoted)
        {
            EmitQuoteAwareDelimitedSplitting(sb, model, fields, fieldCount, hasMultiLine);
            return;
        }

        // FDEL-02: Per-field delimiter support
        // For each field, determine its delimiter: field-specific override or record-level default
        string recordDelim = model.Delimiter;

        // Phase 14 MLIN-02: Track which line we're on for multi-line records
        int currentLine = 0;
        string currentLineVar = hasMultiLine ? "__line0" : "line";

        for (int i = 0; i < fieldCount; i++)
        {
            var field = model.Fields[i];

            // Phase 14 MLIN-02: If this field starts on a new line, update current line variable
            if (hasMultiLine && i > 0 && field.IsInNewLine)
            {
                currentLine++;
                currentLineVar = $"__line{currentLine}";
                sb.AppendLine($"        // Phase 14 MLIN-02: Field '{field.Name}' is on new line {currentLine}");
            }

            // Per-field delimiter belongs to the following field, so the boundary after
            // field i uses field i+1's override or the record-level default.
            string delim = i < fieldCount - 1 ? fields[i + 1].Delimiter ?? recordDelim : recordDelim;
            bool isSingleChar = delim.Length == 1;
            string delimLiteral = isSingleChar
                ? $"'{EscapeChar(delim[0])}'"
                : $"\"{EscapeString(delim)}\", global::System.StringComparison.Ordinal";
            int delimLen = delim.Length;

            bool isLast = i == fieldCount - 1;
            bool isLastOnThisLine = isLast || (hasMultiLine && i < fieldCount - 1 && fields[i + 1].IsInNewLine);

            if (isLastOnThisLine)
            {
                // Last field on this line: consume remainder of the current line span.
                string srcSpan = i == 0 || (hasMultiLine && field.IsInNewLine)
                    ? currentLineVar
                    : $"__rem{i}";
                sb.AppendLine($"        var __f{i} = {srcSpan};");
            }
            else
            {
                string srcSpan = i == 0 || (hasMultiLine && field.IsInNewLine)
                    ? currentLineVar
                    : $"__rem{i}";
                sb.AppendLine($"        int __sep{i} = {srcSpan}.IndexOf({delimLiteral});");
                sb.AppendLine($"        var __f{i} = __sep{i} >= 0 ? {srcSpan}.Slice(0, __sep{i}) : {srcSpan};");
                sb.AppendLine($"        var __rem{i + 1} = __sep{i} >= 0 ? {srcSpan}.Slice(__sep{i} + {delimLen}) : global::System.ReadOnlySpan<char>.Empty;");
            }
        }
    }

    /// <summary>
    /// WR-04: Emits a quote-aware scanner for delimited records with at least one
    /// <see cref="FieldModel.IsQuoted"/> field. Tracks "inside quotes" state char-by-char
    /// so embedded delimiters inside a quoted payload do not terminate the field early.
    /// The scanner treats doubled quote chars as escapes (RFC 4180) and does not alter
    /// the raw field span — <see cref="EmitFieldQuotedStripPass"/> still strips the outer
    /// quote wrapper and unescapes doubled internals afterwards.
    /// Delimiter is assumed to be a single char for the fast path; multi-char delimiters
    /// fall back to a per-char scan matching the literal sequence.
    /// FDEL-02: Per-field delimiter support — each field can have its own delimiter override.
    /// Phase 14 MLIN-02: For multi-line records, fields with IsInNewLine use their corresponding line.
    /// </summary>
    private static void EmitQuoteAwareDelimitedSplitting(
        StringBuilder sb,
        RecordModel model,
        EquatableArray<FieldModel> fields,
        int fieldCount,
        bool hasMultiLine = false)
    {
        // FDEL-02: For quote-aware splitting with per-field delimiters, we need to
        // determine the delimiter for each field. The quote scanner advances char-by-char
        // and needs to know which delimiter to check for at each field boundary.
        string recordDelim = model.Delimiter;

        // Determine the quote character. In practice FH 3.x uses a single quote char per record;
        // we use the first quoted field's QuoteChar as the canonical one and assume all quoted
        // fields agree. Mixed quote chars on one record remain a v1.1 nicety.
        char qc = '"';
        for (int i = 0; i < fieldCount; i++)
        {
            if (fields[i].IsQuoted) { qc = fields[i].QuoteChar; break; }
        }
        string qLit = $"'{EscapeChar(qc)}'";

        sb.AppendLine("        // WR-04: quote-aware delimited splitting — delimiters inside the");
        sb.AppendLine("        // quoted payload do not terminate the field. Doubled quote chars inside");
        sb.AppendLine("        // a quoted span are treated as escape pairs and kept raw here —");
        sb.AppendLine("        // EmitFieldQuotedStripPass strips the outer quotes and collapses pairs.");

        // Phase 14 MLIN-02: Track which line we're on for multi-line records
        int currentLine = 0;

        for (int i = 0; i < fieldCount; i++)
        {
            var field = model.Fields[i];

            // Phase 14 MLIN-02: If this field starts on a new line, update current line
            if (hasMultiLine && i > 0 && field.IsInNewLine)
            {
                currentLine++;
                sb.AppendLine($"        // Phase 14 MLIN-02: Field '{field.Name}' is on new line {currentLine}");
            }

            string currentLineVar = hasMultiLine ? $"__line{currentLine}" : "line";
            string srcSpan = i == 0 || (hasMultiLine && field.IsInNewLine)
                ? currentLineVar
                : $"__qrem{i}";

            // FDEL-02: delimiter before the next field uses that next field's override.
            string delim = i < fieldCount - 1 ? fields[i + 1].Delimiter ?? recordDelim : recordDelim;
            bool isSingleChar = delim.Length == 1;
            string delimFirst = $"'{EscapeChar(delim[0])}'";

            bool isLast = i == fieldCount - 1;
            bool isLastOnThisLine = isLast || (hasMultiLine && i < fieldCount - 1 && fields[i + 1].IsInNewLine);

            sb.AppendLine($"        int __qsStart{i} = 0;");

            if (isLastOnThisLine)
            {
                // Consume remainder of this line. Quote state is still correct up to EOL.
                sb.AppendLine($"        var __f{i} = {srcSpan}.Slice(__qsStart{i});");
            }
            else
            {
                sb.AppendLine($"        int __qsPos{i} = 0;");
                sb.AppendLine($"        int __qsLen{i} = {srcSpan}.Length;");
                // Inline the scanner with a state local scoped to THIS field's loop.
                // Use a distinct local name per field (e.g. __qsIn0, __qsIn1) to avoid
                // cross-field shadowing at the method scope.
                // OPT: Use IndexOfAny to skip non-quote/non-delimiter characters in SIMD jumps.
                sb.AppendLine($"        bool __qsIn{i} = false;");
                string delimCh = isSingleChar ? delimFirst : $"'{EscapeChar(delim[0])}'";
                sb.AppendLine($"        while (__qsPos{i} < __qsLen{i})");
                sb.AppendLine("        {");
                // Use IndexOfAny to jump to next quote or first char of delimiter
                sb.AppendLine($"            int __qsJump{i} = {srcSpan}[__qsPos{i}..].IndexOfAny({qLit}, {delimCh});");
                sb.AppendLine($"            if (__qsJump{i} < 0) {{ __qsPos{i} = __qsLen{i}; break; }}");
                sb.AppendLine($"            __qsPos{i} += __qsJump{i};");
                sb.AppendLine($"            char __qsCh = {srcSpan}[__qsPos{i}];");
                sb.AppendLine($"            if (__qsCh == {qLit})");
                sb.AppendLine("            {");
                sb.AppendLine("                // Doubled quote inside a quoted span: skip pair and stay inside.");
                sb.AppendLine($"                if (__qsIn{i} && __qsPos{i} + 1 < __qsLen{i} && {srcSpan}[__qsPos{i} + 1] == {qLit})");
                sb.AppendLine("                {");
                sb.AppendLine($"                    __qsPos{i} += 2;");
                sb.AppendLine("                    continue;");
                sb.AppendLine("                }");
                sb.AppendLine($"                __qsIn{i} = !__qsIn{i};");
                sb.AppendLine($"                __qsPos{i}++;");
                sb.AppendLine("                continue;");
                sb.AppendLine("            }");
                if (isSingleChar)
                {
                    sb.AppendLine($"            if (!__qsIn{i} && __qsCh == {delimFirst}) break;");
                }
                else
                {
                    // Multi-char delimiter: check full literal match starting at __qsPos.
                    sb.AppendLine($"            if (!__qsIn{i} && __qsCh == {delimFirst} && __qsPos{i} + {delim.Length} <= __qsLen{i}");
                    for (int di = 1; di < delim.Length; di++)
                    {
                        string delimChLit = $"'{EscapeChar(delim[di])}'";
                        sb.AppendLine($"                && {srcSpan}[__qsPos{i} + {di}] == {delimChLit}");
                    }
                    sb.AppendLine("            ) break;");
                }
                sb.AppendLine($"            __qsPos{i}++;");
                sb.AppendLine("        }");
                sb.AppendLine($"        var __f{i} = {srcSpan}.Slice(__qsStart{i}, __qsPos{i} - __qsStart{i});");
                sb.AppendLine($"        var __qrem{i + 1} = __qsPos{i} < __qsLen{i} ? {srcSpan}.Slice(__qsPos{i} + {delim.Length}) : global::System.ReadOnlySpan<char>.Empty;");
            }
        }
    }

    private static void EmitFixedLengthModeValidation(
        StringBuilder sb,
        EquatableArray<FieldModel> fields,
        int fieldCount,
        string? fixedMode,
        bool hasMultiLine)
    {
        string mode = fixedMode ?? "ExactLength";
        if (string.Equals(mode, "AllowVariableLength", System.StringComparison.Ordinal))
            return;

        int currentLine = 0;
        int[] widthsByLine = new int[fieldCount == 0 ? 1 : fieldCount];
        for (int i = 0; i < fieldCount; i++)
        {
            if (hasMultiLine && i > 0 && fields[i].IsInNewLine)
                currentLine++;

            if (fields[i].FixedLength > 0)
                widthsByLine[currentLine] += fields[i].FixedLength;
        }

        for (int lineIndex = 0; lineIndex <= currentLine; lineIndex++)
        {
            string lineVar = hasMultiLine ? $"__line{lineIndex}" : "line";
            int expectedWidth = widthsByLine[lineIndex];
            string condition = mode switch
            {
                "AllowMoreChars" => $"{lineVar}.Length < {expectedWidth}",
                "AllowLessChars" => $"{lineVar}.Length > {expectedWidth}",
                _ => $"{lineVar}.Length != {expectedWidth}",
            };

            sb.AppendLine($"        if ({condition})");
            sb.AppendLine($"            throw new global::System.FormatException($\"Fixed-length record line {lineIndex + 1} has length {{{lineVar}.Length}} but expected {DescribeFixedModeExpectation(mode, expectedWidth)}.\");");
        }

        sb.AppendLine();
    }

    private static string DescribeFixedModeExpectation(string fixedMode, int expectedWidth) =>
        fixedMode switch
        {
            "AllowMoreChars" => $"at least {expectedWidth} characters",
            "AllowLessChars" => $"at most {expectedWidth} characters",
            _ => $"{expectedWidth} characters",
        };

    /// <summary>
    /// Emits raw <c>line.Slice(offset, width)</c> arithmetic for fixed-length records (D-04: fully inlined).
    /// Using Math.Min for width clamping guards against short lines (D-03: lenient behavior).
    /// Phase 14 MLIN-02: For multi-line records, fields with IsInNewLine use their corresponding line.
    /// </summary>
    private static void EmitFixedLengthFieldSplitting(
        StringBuilder sb,
        EquatableArray<FieldModel> fields,
        int fieldCount,
        bool hasMultiLine = false)
    {
        // Phase 14 MLIN-02: Track which line we're on for multi-line records
        int currentLine = 0;
        string currentLineVar = hasMultiLine ? "__line0" : "line";

        int runningOffset = 0;
        for (int i = 0; i < fieldCount; i++)
        {
            var field = fields[i];

            // Phase 14 MLIN-02: If this field starts on a new line, update current line
            if (hasMultiLine && i > 0 && field.IsInNewLine)
            {
                currentLine++;
                currentLineVar = $"__line{currentLine}";
                runningOffset = 0; // Reset offset for new line
                sb.AppendLine($"        // Phase 14 MLIN-02: Field '{field.Name}' is on new line {currentLine}");
            }

            int offset = runningOffset;
            int width = field.FixedLength > 0 ? field.FixedLength : 0;

            sb.AppendLine($"        var __f{i} = {currentLineVar}.Length > {offset} ? {currentLineVar}.Slice({offset}, global::System.Math.Min({width}, {currentLineVar}.Length - {offset})) : global::System.ReadOnlySpan<char>.Empty;");

            if (field.FixedLength > 0) runningOffset += field.FixedLength;
        }
    }

    /// <summary>
    /// Returns true if any field in the model has <c>IsInitOnly = true</c>.
    /// Used to exclude record-class types with init-only properties from <see cref="IRecyclableDescriptor{T}"/>
    /// emission — init-only properties cannot be assigned outside an object initializer or constructor,
    /// so <c>ParseInto</c> would produce CS8852 if emitted for such types.
    /// </summary>
    private static bool HasAnyInitOnlyField(EquatableArray<FieldModel> fields, int fieldCount)
    {
        for (int i = 0; i < fieldCount; i++)
        {
            if (fields[i].IsInitOnly) return true;
        }
        return false;
    }

    /// <summary>
    /// Returns true if every field in the model has <c>IsInitOnly = true</c>,
    /// indicating positional record constructor syntax is valid.
    /// Field-based structs (e.g., <c>record struct</c> with public fields) return false.
    /// </summary>
    private static bool AllFieldsInitOnly(EquatableArray<FieldModel> fields, int fieldCount)
    {
        for (int i = 0; i < fieldCount; i++)
        {
            if (!fields[i].IsInitOnly) return false;
        }
        return true;
    }

    /// <summary>
    /// Emits the constructor call.
    /// Positional syntax (<c>new T(v0, v1)</c>) is used only when all fields are init-only
    /// (positional record structs/classes). All other types use object initializer syntax.
    /// FAVL-07, FAVL-10: Fields marked with IsValueDiscarded are skipped in the constructor.
    /// </summary>
    private static void EmitConstructorCall(
        StringBuilder sb,
        string fqType,
        EquatableArray<FieldModel> fields,
        int fieldCount,
        bool usePositionalConstructor)
    {
        // Count visible (non-discarded) fields first
        int visibleCount = 0;
        for (int i = 0; i < fieldCount; i++)
        {
            if (!fields[i].IsValueDiscarded) visibleCount++;
        }

        if (usePositionalConstructor)
        {
            // Positional constructor: new T(__v0, __v1, __v2) - skip discarded fields
            var args = new StringBuilder();
            int visibleIndex = 0;
            for (int i = 0; i < fieldCount; i++)
            {
                if (fields[i].IsValueDiscarded) continue;  // FAVL-07: skip discarded
                if (visibleIndex > 0) args.Append(", ");
                args.Append($"__v{i}");
                visibleIndex++;
            }
            sb.AppendLine($"        return new {fqType}({args});");
        }
        else
        {
            // Object initializer: new T { Prop0 = __v0, Prop1 = __v1, ... } - skip discarded fields
            sb.AppendLine($"        return new {fqType}");
            sb.AppendLine("        {");
            int visibleIndex = 0;
            for (int i = 0; i < fieldCount; i++)
            {
                if (fields[i].IsValueDiscarded) continue;  // FAVL-07: skip discarded
                bool isLastVisible = visibleIndex == visibleCount - 1;
                string comma = isLastVisible ? "" : ",";
                sb.AppendLine($"            {fields[i].Name} = __v{i}{comma}");
                visibleIndex++;
            }
            sb.AppendLine("        };");
        }
    }

    /// <summary>
    /// Returns the inline TryParse (or string construction) statement for a single field.
    /// D-14: decision tree — explicit ConverterKind, custom type, then Phase 5 inline switch,
    /// then DateTime/DateOnly/TimeOnly fallback via built-in converters.
    /// Generator targets netstandard2.0: no range/index syntax; use Substring instead of slice.
    /// </summary>
    private static string GetInlineTryParse(string fieldVar, FieldModel field, int fieldIdx)
    {
        string typeName = field.TypeName;
        string fullTypeName = field.FullTypeName;

        // D-14: Step 1 — explicit ConverterKind annotation
        if (field.ConverterKind != GeneratorConverterKind.None)
        {
            return EmitBuiltInConverterTryParse(fieldVar, field, fieldIdx);
        }

        // D-14: Step 2 — custom type annotation (ConverterBase subclass wrapped in ConverterBaseAdapter<T>)
        if (field.ConverterTypeName is not null)
        {
            return EmitCustomConverterTryParse(fieldVar, field, fieldIdx);
        }

        // D-14: Steps 3–5: no annotation → fall through to Phase 5 inline switch
        // Normalize: strip "global::" prefix and "?" nullable suffix for comparison.
        const string globalPrefix = "global::";
        string normalized = typeName.TrimEnd('?');
        if (normalized.StartsWith(globalPrefix, System.StringComparison.Ordinal))
            normalized = normalized.Substring(globalPrefix.Length);

        // Also normalize fullTypeName for fallback matching.
        string normalizedFull = fullTypeName.TrimEnd('?');
        if (normalizedFull.StartsWith(globalPrefix, System.StringComparison.Ordinal))
            normalizedFull = normalizedFull.Substring(globalPrefix.Length);

        string? result = GetTryParseForNormalizedType(fieldVar, normalized, fieldIdx);
        if (result != null)
            return result;

        result = GetTryParseForNormalizedType(fieldVar, normalizedFull, fieldIdx);
        if (result != null)
            return result;

        // D-14: Step 4 — DateTime/DateOnly/TimeOnly without annotation → built-in converter
        if (string.Equals(normalized, "DateTime", System.StringComparison.Ordinal) ||
            string.Equals(normalizedFull, "System.DateTime", System.StringComparison.Ordinal))
            return $"if (!global::ModernLibs.FileHelpers.Converters.DateTimeConverter.Instance.TryParse({fieldVar}, out var __v{fieldIdx})) __v{fieldIdx} = default;";

        if (string.Equals(normalized, "DateOnly", System.StringComparison.Ordinal) ||
            string.Equals(normalizedFull, "System.DateOnly", System.StringComparison.Ordinal))
            return $"if (!global::ModernLibs.FileHelpers.Converters.DateOnlyConverter.Instance.TryParse({fieldVar}, out var __v{fieldIdx})) __v{fieldIdx} = default;";

        if (string.Equals(normalized, "TimeOnly", System.StringComparison.Ordinal) ||
            string.Equals(normalizedFull, "System.TimeOnly", System.StringComparison.Ordinal))
            return $"if (!global::ModernLibs.FileHelpers.Converters.TimeOnlyConverter.Instance.TryParse({fieldVar}, out var __v{fieldIdx})) __v{fieldIdx} = default;";

        // D-14: Step 5 — Enum without annotation: deferred to Phase 7 (requires IsEnum in FieldModel)
        // Emit default(T) with a comment — implicit enum dispatch requires TypeKind.Enum in FieldModel.
        return $"var __v{fieldIdx} = default({fullTypeName}); // TODO Phase 7: implicit enum dispatch (add IsEnum to FieldModel)";
    }

    /// <summary>
    /// Emits a built-in converter TryParse call for the given ConverterKind.
    /// T-06-04-01: exhaustive switch with InvalidOperationException for unknown values.
    /// </summary>
    private static string EmitBuiltInConverterTryParse(string fieldVar, FieldModel field, int fieldIdx)
    {
        // DateMultiFormat needs constructor args — handled separately with static cached field
        if (field.ConverterKind == GeneratorConverterKind.DateMultiFormat)
            return EmitDateMultiFormatTryParse(fieldVar, field, fieldIdx);

        // Phase 51 GAP-04: Date converters with format string and/or culture need static cached field
        bool isDateConverter = field.ConverterKind == GeneratorConverterKind.Date;

        if (isDateConverter && (field.ConverterArgs.Length > 0 || !string.IsNullOrEmpty(field.CultureName)))
            return EmitDateWithFormatTryParse(fieldVar, field, fieldIdx);

        string converterClass = GetBuiltInConverterClass(field.ConverterKind, field.FullTypeName);

        // Phase 51 GAP-04: use culture-aware converter instance when CultureName is specified
        string converterInstance = GetConverterInstanceExpression(field, converterClass);

        return $"if (!{converterInstance}.TryParse({fieldVar}, out var __v{fieldIdx})) __v{fieldIdx} = default;";
    }

