// would obscure the simple Stack-based pooling flow.
#pragma warning disable MA0051

using System.Buffers;
using System.Diagnostics.CodeAnalysis;

namespace ModernLibs.FileHelpers.Pooling;

/// <summary>
/// Object pool for class-type records. Uses a simple <see cref="Stack{T}"/> with
/// <see cref="ArrayPool{T}"/>-backed storage for the internal array.
/// </summary>
/// <remarks>
/// <para>
/// <strong>Thread safety:</strong> This pool is NOT thread-safe. It is designed for
/// single-threaded per-engine-instance use, which covers the common CSV parsing scenario.
/// For concurrent access, wrap with <c>lock</c> at the call site.
/// </para>
/// <para>
/// <strong>Cold path:</strong> The first time a record is requested and the pool is empty,
/// <see cref="Activator.CreateInstance{T}"/> is used. All record types generated by the
/// source generator have a parameterless constructor.
/// </para>
/// </remarks>
/// <typeparam name="T">Class record type annotated with <c>[DelimitedRecord]</c> or <c>[FixedLengthRecord]</c>.</typeparam>
public sealed class RecordPool<[DynamicallyAccessedMembers(DynamicallyAccessedMemberTypes.PublicParameterlessConstructor)] T> : IDisposable where T : class
{
    private readonly Stack<T> _pool;
    private bool _disposed;

    /// <summary>
    /// Creates a new record pool with the specified initial capacity.
    /// </summary>
    /// <param name="initialCapacity">Initial stack capacity. Defaults to 16.</param>
    public RecordPool(int initialCapacity = 16)
    {
        ArgumentOutOfRangeException.ThrowIfNegativeOrZero(initialCapacity);
        _pool = new Stack<T>(initialCapacity);
    }

    /// <summary>
    /// Returns the number of records currently in the pool.
    /// </summary>
    public int Count => _pool.Count;

    /// <summary>
    /// Rents a record from the pool. If the pool is empty, creates a new instance
    /// via <see cref="Activator.CreateInstance{T}"/>.
    /// </summary>
    /// <returns>A record instance ready for reuse.</returns>
    /// <exception cref="ObjectDisposedException">Thrown when the pool has been disposed.</exception>
    public T Rent()
    {
        ObjectDisposedException.ThrowIf(_disposed, this);
        return _pool.Count > 0 ? _pool.Pop() : Activator.CreateInstance<T>()!;
    }

    /// <summary>
    /// Returns a record to the pool for future reuse.
    /// </summary>
    /// <param name="record">The record to return. Must not be null.</param>
    /// <exception cref="ObjectDisposedException">Thrown when the pool has been disposed.</exception>
    public void Return(T record)
    {
        ObjectDisposedException.ThrowIf(_disposed, this);
        ArgumentNullException.ThrowIfNull(record);
        _pool.Push(record);
    }

    /// <summary>
    /// Clears all records from the pool without disposing them.
    /// </summary>
    public void Clear()
    {
        ObjectDisposedException.ThrowIf(_disposed, this);
        _pool.Clear();
    }

    /// <summary>
    /// Disposes the pool and clears all pooled records. The pool cannot be used after disposal.
    /// </summary>
    public void Dispose()
    {
        if (!_disposed)
        {
            _disposed = true;
            _pool.Clear();
        }
    }
}
