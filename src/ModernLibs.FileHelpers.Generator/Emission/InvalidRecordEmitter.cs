using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using ModernLibs.FileHelpers.Generator.Models;

namespace ModernLibs.FileHelpers.Generator.Emission;

/// <summary>
/// Emits the descriptor registered for a record type that has FileHelpers errors. Every member throws a
/// <c>BadUsageException</c> that names the record and its errors.
/// </summary>
/// <remarks>
/// The errors are reported by <see cref="FileHelpersAnalyzer"/> and fail the build, so this code only runs
/// when they were hidden: with <c>[SuppressMessage]</c> (which, unlike <c>#pragma</c> and severity
/// configuration, also applies to not-configurable diagnostics) or with analyzers turned off
/// (<c>RunAnalyzers=false</c>). Without it the engine would fail with a generic "no descriptor registered"
/// message, or a converter would be ignored silently.
/// </remarks>
internal static class InvalidRecordEmitter
{
    internal static void Emit(SourceProductionContext spc, RecordModel model, IReadOnlyList<string> errors) =>
        spc.AddSource(model.HintName, Microsoft.CodeAnalysis.Text.SourceText.From(Generate(model, errors), Encoding.UTF8));

    internal static string Generate(RecordModel model, IReadOnlyList<string> errors)
    {
        string fqType = model.FullyQualifiedName;
        string displayName = fqType.Replace("global::", string.Empty);
        string message = $"No descriptor was generated for '{displayName}' because the record has FileHelpers errors, " +
                         "which were hidden from the build ([SuppressMessage] or analyzers turned off). Fix them: "
                         + string.Join(" ", errors);
        string descriptorName = $"__{model.TypeName}InvalidDescriptor";
        const string Throw = " => throw new global::ModernLibs.FileHelpers.BadUsageException(Message);";

        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated/>");
        sb.AppendLine("#nullable enable");
        sb.AppendLine("#pragma warning disable CA2255 // ModuleInitializer in source-generated consumer code");
        sb.AppendLine("#pragma warning disable CS0612, CS0618 // obsolete record type");
        sb.AppendLine();
        if (!string.IsNullOrEmpty(model.Namespace))
        {
            sb.AppendLine($"namespace {model.Namespace};");
            sb.AppendLine();
        }

        sb.AppendLine($"file sealed class {descriptorName} : global::ModernLibs.FileHelpers.IRecordDescriptor<{fqType}>");
        sb.AppendLine("{");
        sb.AppendLine($"    public static readonly {descriptorName} Instance = new();");
        sb.AppendLine();
        sb.AppendLine($"    private const string Message = {SymbolDisplay.FormatLiteral(message, quote: true)};");
        sb.AppendLine();
        sb.AppendLine($"    public {fqType} Parse(global::System.ReadOnlySpan<char> lines, int lineCount){Throw}");
        sb.AppendLine($"    public void Format({fqType} record, global::System.Buffers.IBufferWriter<char> writer){Throw}");
        sb.AppendLine($"    public global::System.ReadOnlySpan<global::ModernLibs.FileHelpers.FieldDescriptor> Fields{Throw}");
        sb.AppendLine($"    public global::ModernLibs.FileHelpers.RecordOptions Options{Throw}");
        sb.AppendLine($"    public {fqType} CreateDefaultInstance(){Throw}");
        sb.AppendLine("}");
        sb.AppendLine();
        sb.AppendLine($"file static class __{model.TypeName}Registration");
        sb.AppendLine("{");
        sb.AppendLine("    [global::System.Runtime.CompilerServices.ModuleInitializer]");
        sb.AppendLine("    internal static void Register()");
        sb.AppendLine("    {");
        sb.AppendLine($"        global::ModernLibs.FileHelpers.FileHelperRegistry<{fqType}>");
        sb.AppendLine($"            .SetDescriptor({descriptorName}.Instance);");
        sb.AppendLine("    }");
        sb.AppendLine("}");
        return sb.ToString();
    }
}
