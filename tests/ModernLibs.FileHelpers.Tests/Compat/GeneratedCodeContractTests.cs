/// <summary>
/// Descriptors generated by 4.8 and 4.9 are compiled into consumer assemblies and bind to the members listed in
/// <c>docs/GENERATED-CODE-CONTRACT.md</c>. Each entry below is one row (or one member of a row) of that table:
/// the member must exist with exactly the listed parameter types.
/// </summary>
[Category("Compat")]
public sealed class GeneratedCodeContractTests
{
    /// <summary>Stands for the record type <c>T</c> of the generic contract types.</summary>
    private sealed class Rec;

    private const BindingFlags Any = BindingFlags.Public | BindingFlags.Instance | BindingFlags.Static | BindingFlags.DeclaredOnly;

    private static readonly Type SpanOfChar = typeof(ReadOnlySpan<char>);

    private static readonly (string Member, Func<bool> Exists)[] Contract =
    [
        // IRecordDescriptor<T> (Emitter:61, :487, :1307, :90, :1408, :98)
        Method(typeof(IRecordDescriptor<Rec>), "Parse", typeof(Rec), SpanOfChar, typeof(int)),
        ("IRecordDescriptor<T>.Parse(ReadOnlySpan<char>) with a default body", () =>
            typeof(IRecordDescriptor<Rec>).GetMethod("Parse", Any, [SpanOfChar]) is { IsAbstract: false } m && m.ReturnType == typeof(Rec)),
        Method(typeof(IRecordDescriptor<Rec>), "Format", typeof(void), typeof(Rec), typeof(IBufferWriter<char>)),
        Property(typeof(IRecordDescriptor<Rec>), "Fields", typeof(ReadOnlySpan<FieldDescriptor>)),
        Property(typeof(IRecordDescriptor<Rec>), "Options", typeof(RecordOptions)),
        Method(typeof(IRecordDescriptor<Rec>), "CreateDefaultInstance", typeof(Rec)),

