using TUnit.Core;

namespace ModernLibs.FileHelpers.Tests.Compat;

/// <summary>
/// A library compiled against 4.9.1 carries descriptors generated by the 4.9.1 generator (Generated49). On the
/// current runtime they must read, report errors and write exactly as the descriptors the current generator
/// makes for the same record (the <c>...Twin</c> types).
/// </summary>
[Category("Compat")]
public sealed class Compat49Tests
{
    [Test]
    [DisplayName("A 4.9.1 descriptor reads and writes as the current one: $name")]
    [MethodDataSource(typeof(Compat49Matrix), nameof(Compat49Matrix.All))]
    public async Task Descriptor_From_4_9_1_Matches_The_Current_One(
        string name, Func<string, string> readOld, Func<string, string> readNew,
        Func<string, string> roundTripOld, Func<string, string> roundTripNew)
    {
        foreach (string input in Compat49Inputs.For(name))   // at least: valid rows, a short row, a long row,
        {                                                    // a bad value, an unclosed quote, an empty line
            await Assert.That(readOld(input)).IsEqualTo(readNew(input));
            await Assert.That(roundTripOld(input)).IsEqualTo(roundTripNew(input));
        }
    }

    [Test]
    [DisplayName("Compat49Inputs.FieldCount is the field count of both descriptors: $name")]
    [MethodDataSource(typeof(Compat49Matrix), nameof(Compat49Matrix.FieldCounts))]
    public async Task FieldCount_Matches_Both_Descriptors(string name, int oldCount, int newCount)
    {
        await Assert.That(Compat49Inputs.FieldCount(name)).IsEqualTo(oldCount);
        await Assert.That(newCount).IsEqualTo(oldCount);
    }

    [Test]
    [DisplayName("The matrix covers the 19 record shapes, each with inputs")]
    public async Task Matrix_Covers_Every_Shape()
    {
        var names = Compat49Matrix.All().Select(c => c.Name).ToArray();

        await Assert.That(names.Length).IsEqualTo(19);
        await Assert.That(names.Distinct(StringComparer.Ordinal).Count()).IsEqualTo(19);
        foreach (string name in names)
            await Assert.That(Compat49Inputs.For(name).Count()).IsGreaterThanOrEqualTo(6);
    }
}
